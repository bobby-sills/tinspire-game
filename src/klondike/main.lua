-- ------------------------------------------------------------ the board --

-- Where a pile's outline goes. For a tableau column that is the exposed card,
-- clipped to the tableau, so a highlight never escapes downwards even when the
-- column is long enough that the last card is cut off.
local function pileRect(sel)
  local bot = ui.tabY + ui.tabH
  if sel.where == "stock" then
    return slotX(1), ui.topY, CARD_W, CARD_H
  elseif sel.where == "waste" then
    local n = #game.waste
    local shown = (game.drawCount == 3) and math.min(3, n) or math.min(1, n)
    local x = slotX(2) + math.max(0, shown - 1) * WASTE_FAN
    return x, ui.topY, CARD_W, CARD_H
  elseif sel.where == "found" then
    return slotX(3 + sel.a), ui.topY, CARD_W, CARD_H
  elseif sel.where == "tab" then
    local ys = columnYs(sel.a)
    local n = #ys
    if n == 0 then return slotX(sel.a), ui.tabY, CARD_W, CARD_H end
    local i = sel.i
    if not i or i < 1 or i > n then i = n end
    local y = ys[i]
    local h = math.min(CARD_H, bot - y)
    -- A held run is outlined as one block from its first card to the bottom.
    if i < n then h = math.min(ys[n] + CARD_H, bot) - y end
    return slotX(sel.a), y, CARD_W, math.max(0, h)
  end
end

local function drawWaste(gc)
  local n = #game.waste
  if n == 0 then
    drawSlot(gc, slotX(2), ui.topY, nil)
    return
  end
  -- Draw-3 spreads the turned cards into the gap beside the waste, the way a
  -- real deal does, so you can see what is coming even though only the last
  -- one is playable. Draw-1 has nothing to spread.
  local shown = (game.drawCount == 3) and math.min(3, n) or 1
  for k = shown, 1, -1 do
    local card = game.waste[n - k + 1]
    drawCard(gc, slotX(2) + (shown - k) * WASTE_FAN, ui.topY, card,
             ui.topY, ui.topY + CARD_H)
  end
end

local function drawTopRow(gc, dests)
  -- Stock. An empty stock that can still be recycled keeps its outline; one
  -- that cannot is dimmed to the felt, because that is the game telling you
  -- the passes have run out.
  if #game.stock > 0 then
    drawCard(gc, slotX(1), ui.topY, BACK, ui.topY, ui.topY + CARD_H)
  else
    drawSlot(gc, slotX(1), ui.topY, nil)
    if game:canRecycle() then
      outline(gc, slotX(1), ui.topY, CARD_W, CARD_H, SLOT_LINE, 1)
    end
  end

  drawWaste(gc)

  for f = 1, Klondike.SUITS do
    local x = slotX(3 + f)
    local top = game:foundTop(f)
    if top then
      drawCard(gc, x, ui.topY, top, ui.topY, ui.topY + CARD_H)
    else
      drawSlot(gc, x, ui.topY, f)
    end
    if dests["found:" .. f] then
      outline(gc, x, ui.topY, CARD_W, CARD_H, DEST_COL)
    end
  end
end

local function drawTableau(gc, dests)
  local bot = ui.tabY + ui.tabH
  for c = 1, COLUMNS do
    local col_, ys = game.tab[c], columnYs(c)
    local x = slotX(c)
    if #col_ == 0 then
      drawSlot(gc, x, ui.tabY, nil)
    else
      for i = 1, #col_ do
        -- Only the strip a player can actually see is drawn: the next card
        -- covers everything below its own top edge.
        local top = ys[i]
        local cardBot = math.min(ys[i] + CARD_H, bot)
        if i < #col_ then cardBot = math.min(cardBot, ys[i + 1]) end
        local idx = (i <= game.down[c]) and BACK or col_[i]
        drawCard(gc, x, top, idx, top, cardBot)
      end
    end
    if dests["tab:" .. c] then
      local rx, ry, rw, rh = pileRect({ where = "tab", a = c })
      outline(gc, rx, ry, rw, rh, DEST_COL)
    end
  end
end

-- ----------------------------------------------------------------- HUD --

local function drawHud(gc)
  col(gc, HUD_BG)
  gc:fillRect(0, 0, ui.w, HUD_H)
  col(gc, HUD_RULE)
  gc:fillRect(0, HUD_H - 1, ui.w, 1)

  gc:setFont("sansserif", "r", 10)
  local th = gc:getStringHeight("Ay")
  local ty = math.max(0, math.floor((HUD_H - 1 - th) / 2))

  local left = message or string.format("Score %d", game.score)
  local mid = string.format("%d/52", game:foundationTotal())
  local right = string.format("Moves %d", game.moves)
  if game.maxPasses then
    right = string.format("Pass %d/%d", game.passes, game.maxPasses)
  end

  -- Sized from the font, never from a character count: the handheld's font is
  -- not the one the previews measure with, and a bar laid out against the
  -- wrong number overlaps itself.
  col(gc, message and ACCENT or INK)
  gc:drawString(left, 4, ty, "top")
  local usedL = 4 + gc:getStringWidth(left)

  col(gc, INK_DIM)
  local rw = gc:getStringWidth(right)
  local rx = ui.w - 4 - rw
  if rx > usedL + 8 then gc:drawString(right, rx, ty, "top") else rx = ui.w - 4 end

  local mw = gc:getStringWidth(mid)
  local mx = math.floor((ui.w - mw) / 2)
  if mx > usedL + 6 and mx + mw < rx - 6 then
    col(gc, ACCENT)
    gc:drawString(mid, mx, ty, "top")
  end
end

-- --------------------------------------------------------------- panels --

-- A centred card of text. `lines` are { text, sel = bool, dim = bool }, and
-- `alt` gives shorter wordings for a window too narrow for the first.
local function drawPanel(gc, title, lines)
  local pad = 10
  gc:setFont("sansserif", "b", 16)
  local titleH, titleW = gc:getStringHeight(title), gc:getStringWidth(title)
  gc:setFont("sansserif", "r", 10)
  local lineH = gc:getStringHeight("Ay")

  local availW = ui.w - 8 - pad * 2
  local texts, maxW = {}, titleW
  for i, l in ipairs(lines) do
    local text = l[1]
    for _, shorter in ipairs(l.alt or {}) do
      if gc:getStringWidth(text) <= availW then break end
      text = shorter
    end
    texts[i] = text
    local w = gc:getStringWidth(text)
    if w > maxW then maxW = w end
  end

  local bw = math.min(maxW + pad * 2, ui.w - 8)
  local bh = titleH + 8 + #lines * lineH + pad * 2
  if bh > ui.h - 8 then
    pad = math.max(2, pad - math.ceil((bh - (ui.h - 8)) / 2))
    bh = math.min(titleH + 8 + #lines * lineH + pad * 2, ui.h - 8)
  end
  local bx = math.max(4, math.floor((ui.w - bw) / 2))
  local by = math.max(4, math.floor((ui.h - bh) / 2))

  col(gc, PANEL_BG)
  gc:fillRect(bx, by, bw, bh)
  outline(gc, bx, by, bw, bh, ACCENT, 1)

  gc:setFont("sansserif", "b", 16)
  col(gc, ACCENT)
  centreText(gc, title, bx, by + pad, bw)

  gc:setFont("sansserif", "r", 10)
  local y = by + pad + titleH + 8
  for i, l in ipairs(lines) do
    if y + lineH > by + bh - 2 then break end
    col(gc, l.sel and ACCENT or (l.dim and INK_DIM or INK))
    centreText(gc, texts[i], bx, y, bw)
    y = y + lineH
  end
end

local function menuLines()
  local lines = {}
  for i, r in ipairs(MENU_ROWS) do
    lines[#lines + 1] = {
      r.label .. ": " .. r.opts[menu[r.key]],
      sel = (menu.row == i),
      alt = { r.opts[menu[r.key]] },
    }
  end
  lines[#lines + 1] = { "", dim = true }
  lines[#lines + 1] = { "arrows: choose      enter: deal",
                        alt = { "arrows / enter" }, dim = true }
  return lines
end

local function drawTooSmall(gc)
  drawPanel(gc, "Klondike", {
    { "This window is too small for a deal.", alt = { "Window too small" } },
    { string.format("The cards need %d x %d.", MIN_W, MIN_H),
      alt = { "Make it bigger" }, dim = true },
  })
end

-- ----------------------------------------------------------------- paint --

function on.paint(gc)
  -- The colour memo is per-frame: the runtime hands out a fresh context each
  -- time, so carrying a remembered colour across frames would skip a set that
  -- was actually needed.
  curR, curG, curB = nil, nil, nil

  col(gc, PAGE_BG)
  gc:fillRect(0, 0, ui.w, ui.h)

  if not ui.fits then
    drawTooSmall(gc)
    return
  end

  -- Destinations are highlighted for whatever the cursor is on, held or not.
  -- Not having to pick a card up to find out where it could go is most of what
  -- makes this playable on a screen this size.
  local sel = held or cur
  local dests = (state == "playing") and destSet(sel) or {}

  drawTopRow(gc, dests)
  drawTableau(gc, dests)

  if state == "playing" then
    local rx, ry, rw, rh = pileRect(cur)
    if rh > 0 then outline(gc, rx, ry, rw, rh, CURSOR_COL) end
    if held then
      local hx, hy, hw, hh = pileRect(held)
      if hh > 0 then outline(gc, hx, hy, hw, hh, SEL_COL) end
    end
  end

  drawHud(gc)

  if state == "menu" then
    drawPanel(gc, "Klondike", menuLines())
  elseif state == "paused" then
    drawPanel(gc, "Paused", {
      { "U undo    R restart    N new deal",
        alt = { "U undo  R restart", "U / R / N" }, dim = true },
      { "M menu", dim = true },
      { "enter: back to the game", alt = { "enter" } },
    })
  elseif state == "won" then
    drawPanel(gc, "You win", {
      { string.format("%d moves, score %d", game.moves, game.score),
        alt = { string.format("score %d", game.score) } },
      { "enter: another deal    M: menu", alt = { "enter / M" }, dim = true },
    })
  elseif state == "playing" and game:isStuck() then
    drawPanel(gc, "Stuck", {
      { "No legal moves left.", alt = { "No moves" } },
      { "U undo    N new deal", alt = { "U / N" }, dim = true },
    })
  end
end

