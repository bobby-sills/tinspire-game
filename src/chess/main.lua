  gc:setFont("sansserif", "b", 10)
  local titleW = gc:getStringWidth("CHESS")

  local right = MODE_SHORT[menu.mode]
  if menu.mode == 2 then right = right .. "  " .. level().name end
  gc:setFont("sansserif", "r", 10)
  local rx = ui.w - gc:getStringWidth(right) - MARGIN

  -- The mode and level matter more than the title, so the title is what
  -- yields when a narrow window or a wider font pushes them together.
  if rx > titleW + 12 then
    gc:setFont("sansserif", "b", 10)
    col(gc, ACCENT); gc:drawString("CHESS", MARGIN, 3, "top")
    gc:setFont("sansserif", "r", 10)
  end
  col(gc, INK_DIM); gc:drawString(right, math.max(2, rx), 3, "top")
end

-- The 64 squares in two colour changes: fill the whole board dark, then paint
-- the light squares over it. Setting a colour is a call, and doing it per
-- square would be sixty-four of them every frame.
local function drawSquares(gc)
  local bx, by, cell, n = ui.bx, ui.by, ui.cell, ui.board
  col(gc, RIM_COL); gc:fillRect(bx - RIM, by - RIM, n + RIM * 2, n + RIM * 2)
  col(gc, DARK); gc:fillRect(bx, by, n, n)
  col(gc, LIGHT)
  for r = 0, 7 do
    for c = 0, 7 do
      if Chess.isLight(squareAt(c, r)) then
        gc:fillRect(bx + c * cell, by + r * cell, cell, cell)
      end
    end
  end
end

local function fillSquare(gc, sq, light, dark)
  local c, r = cellOf(sq)
  col(gc, light and (Chess.isLight(sq) and light or dark) or dark)
  gc:fillRect(ui.bx + c * ui.cell, ui.by + r * ui.cell, ui.cell, ui.cell)
end

local function drawHighlights(gc)
  local last = game:lastMove()
  if last then
    fillSquare(gc, last.from, LIGHT_LAST, DARK_LAST)
    fillSquare(gc, last.to, LIGHT_LAST, DARK_LAST)
  end
  if sel then fillSquare(gc, sel, LIGHT_SEL, DARK_SEL) end
  -- A king in check is the one thing on this board a player must not miss, so
  -- it outranks every other highlight and is painted in a colour used nowhere
  -- else on the screen. It stays up after mate, where it is the answer to
  -- "why is that the end" -- which is exactly when a beginner asks.
  if game.state ~= "ready" and game:inCheck() then
    fillSquare(gc, game:kingSq(game.side), nil, CHECK_SQ)
  end
end

-- Paints one sprite layer -- every piece of one side, one run list each -- in
-- a single colour. Called four times a frame, which is the whole reason the
-- runs are grouped this way: setting a colour is a call, and a thousand rects
-- in four colours costs four of them rather than a thousand.
local function drawRuns(gc, runs, x, y)
  for k = 1, #runs, 3 do
    gc:fillRect(x + runs[k + 1], y + runs[k], runs[k + 2], 1)
  end
end

-- One piece at an arbitrary spot: one blit, or rim then silhouette where the
-- images could not be built. Used by the promotion chooser, which shows the
-- four pieces exactly as they will look on the board.
local function drawSprite(gc, pieceType, side, x, y)
  if sprites then
    gc:drawImage(sprites[pieceType][side], x, y)
    return
  end
  local sprite = SPRITES[pieceType]
  col(gc, (side == WHITE) and W_EDGE or B_EDGE)
  drawRuns(gc, sprite.edge, x, y)
  col(gc, (side == WHITE) and W_FILL or B_FILL)
  drawRuns(gc, sprite.fill, x, y)
end

local function drawSpriteLayer(gc, side, layer, colour, inset)
  local cell, bx, by = ui.cell, ui.bx, ui.by
  local list, cnt = game.plist[side], game.pcount[side]
  col(gc, colour)
  for i = 1, cnt do
    local sq = list[i]
    local c, r = cellOf(sq)
    drawRuns(gc, SPRITES[Chess.TYPE[game.board[sq]]][layer],
      bx + c * cell + inset, by + r * cell + inset)
  end
end

-- The fallback for squares too small for the art: a letter on a disc.
--
-- Text is anchored "top" and centred by hand from getStringHeight, here and
-- everywhere else in this file. The Nspire's "middle" anchor would do the
-- vertical half itself, but the preview renderer draws from the top left, so
-- anchoring by hand is what keeps `make screenshots` honest about the layout.
local function drawLetterPieces(gc)
  local cell, bx, by = ui.cell, ui.bx, ui.by
  local d = math.max(2, cell - 4)
  local off = math.floor((cell - d) / 2)
  gc:setFont("sansserif", "b", ui.pieceSize)

  for side = 1, 2 do
    local list, cnt = game.plist[side], game.pcount[side]
    col(gc, (side == WHITE) and W_DISC or B_DISC)
    for i = 1, cnt do
      local c, r = cellOf(list[i])
      gc:fillArc(bx + c * cell + off, by + r * cell + off, d, d, 0, 360)
    end
    col(gc, (side == WHITE) and W_INK or B_INK)
    for i = 1, cnt do
      local sq = list[i]
      local ch = Chess.LETTER[Chess.TYPE[game.board[sq]]]
      local c, r = cellOf(sq)
      -- Centred, but never centred *out* of the square: on a window dragged
      -- small enough the smallest font is still taller than a cell, and a
      -- negative offset would put the top rank's letters above the board.
      local dx = math.floor((cell - gc:getStringWidth(ch)) / 2)
      local dy = math.floor((cell - gc:getStringHeight(ch)) / 2)
      if dx < 0 then dx = 0 end
      if dy < 0 then dy = 0 end
      gc:drawString(ch, bx + c * cell + dx, by + r * cell + dy, "top")
    end
  end
end

-- Every piece of one side, one blit each. The rim travels inside the image, so
-- unlike the run path this needs no layering to keep a piece's outline out of
-- its neighbour: an image is opaque only where the piece is, and the pieces do
-- not overlap.
local function blitPieces(gc, side, inset)
  local cell, bx, by = ui.cell, ui.bx, ui.by
  local list, cnt = game.plist[side], game.pcount[side]
  local imgs, board, TYPE = sprites, game.board, Chess.TYPE
  for i = 1, cnt do
    local sq = list[i]
    local c, r = cellOf(sq)
    gc:drawImage(imgs[TYPE[board[sq]]][side],
      bx + c * cell + inset, by + r * cell + inset)
  end
end

local function drawPieces(gc)
  if not ui.sprites then return drawLetterPieces(gc) end
  local inset = ui.spriteInset
  if sprites then
    blitPieces(gc, WHITE, inset)
    blitPieces(gc, BLACK, inset)
    return
  end
  -- The rim first, then the silhouette over it, so a piece's own outline can
  -- never eat into the piece next to it.
  drawSpriteLayer(gc, WHITE, "edge", W_EDGE, inset)
  drawSpriteLayer(gc, BLACK, "edge", B_EDGE, inset)
  drawSpriteLayer(gc, WHITE, "fill", W_FILL, inset)
  drawSpriteLayer(gc, BLACK, "fill", B_FILL, inset)
end

-- Where the picked-up piece may go. On a board this small, showing every
-- destination is the difference between playing and guessing -- a dot for a
-- quiet move, a ring for a capture, so the two read differently at a glance.
local function drawDests(gc)
  if not sel or nDests == 0 then return end
  local cell, bx, by = ui.cell, ui.bx, ui.by
  local dot = math.max(2, math.floor(cell / 4))
  local inset = math.floor((cell - dot) / 2)
  col(gc, DEST)
  for i = 1, nDests do
    local to = Chess.moveTo(dests[i])
    local c, r = cellOf(to)
    local x, y = bx + c * cell, by + r * cell
    if game.board[to] == Chess.EMPTY and Chess.moveFlag(dests[i]) ~= Chess.FLAG_EP then
      gc:fillArc(x + inset, y + inset, dot, dot, 0, 360)
    else
      gc:drawRect(x + 1, y + 1, cell - 3, cell - 3)
      gc:drawRect(x + 2, y + 2, cell - 5, cell - 5)
    end
  end
end

local function drawCursor(gc)
  if game.state ~= "playing" or phase == "thinking" or promo then return end
  local c, r = cellOf(cursor)
  local x, y = ui.bx + c * ui.cell, ui.by + r * ui.cell
  col(gc, CURSOR)
  gc:drawRect(x, y, ui.cell - 1, ui.cell - 1)
  gc:drawRect(x + 1, y + 1, ui.cell - 3, ui.cell - 3)
end

local function drawLabels(gc)
  if not ui.labels then return end
  gc:setFont("sansserif", "r", 9)
  col(gc, INK_DIM)
  local cell = ui.cell
  for i = 0, 7 do
    local f = string.char(96 + Chess.fileOf(squareAt(i, 7)))
    gc:drawString(f,
      ui.bx + i * cell + math.floor((cell - gc:getStringWidth(f)) / 2),
      ui.by + ui.board + RIM + 1, "top")
    local rk = tostring(Chess.rankOf(squareAt(0, i)))
    gc:drawString(rk,
      math.max(0, ui.bx - RIM - 2 - gc:getStringWidth(rk)),
      ui.by + i * cell + math.floor((cell - gc:getStringHeight(rk)) / 2), "top")
  end
end

-- ----------------------------------------------------------------- sidebar --

local RESULT_TEXT = {
  checkmate  = "Checkmate",
  stalemate  = "Stalemate",
  fifty      = "Draw: 50 moves",
  repetition = "Draw: repetition",
  material   = "Draw: material",
}

local function statusLine()
  if phase == "thinking" then
    -- The depth the bot is on, which is the honest measure of how much of its
    -- budget it has spent. tests/chess/frame.lua reads this string back.
    local d = ai and math.max(1, ai.completedDepth or ai.searchDepth or 1) or 1
    return "Thinking d" .. d, ACCENT
  end
  local r = game.result
  if r then return RESULT_TEXT[r.kind] or "Game over", ACCENT end
  if game.state == "paused" then return "Paused", INK_DIM end
  if game.state == "playing" and game:inCheck() then return "CHECK", CHECK_SQ end
  return nil
end

-- The pieces `side` has taken, as repeated letters, biggest first.
local function takenText(side, out)
  local n = game:capturedBy(side, out)
  local parts = {}
  for t = 5, 1, -1 do
    for _ = 1, n[t] do parts[#parts + 1] = Chess.LETTER[t] end
  end
  return table.concat(parts)
end

local takenBuf = {}

local function drawSidebar(gc)
  if not ui.sidebar then return end
  local x, w = ui.sx, ui.sw
  local top, bottom = ui.by - RIM, ui.by + ui.board + RIM
  local y = top

  -- Every line checks it still has room before it draws. The handheld always
  -- has enough; a window dragged short simply loses the lines at the bottom
  -- rather than spilling over the edge of the board.
  local function line(gc_, text, colour, size, style)
    local h = size + 3
    if y + h > bottom then return false end
    gc_:setFont("sansserif", style or "r", size)
    if gc_:getStringWidth(text) > w then fitFont(gc_, text, w, style or "r") end
    col(gc_, colour)
    gc_:drawString(text, x, y, "top")
    y = y + h
    return true
  end

  -- Whose move it is, as a chip in that side's own colours -- the same disc
  -- treatment as the pieces, so there is nothing to learn.
  local chip = math.min(12, ui.cell - 2)
  if chip >= 6 and y + chip + 2 <= bottom then
    col(gc, (game.side == WHITE) and W_DISC or B_DISC)
    gc:fillArc(x, y + 1, chip, chip, 0, 360)
    col(gc, INK)
    gc:setFont("sansserif", "b", 10)
    local chipText = SIDE_NAME[game.side] .. " to move"
    gc:drawString(chipText, x + chip + 4,
      y + 1 + math.floor((chip - gc:getStringHeight(chipText)) / 2), "top")
    y = y + chip + 4
  end

  local status, statusCol = statusLine()
  if status then line(gc, status, statusCol, 10, "b") end

  if y + 6 <= bottom then
    col(gc, HUD_RULE); gc:drawLine(x, y + 2, x + w, y + 2); y = y + 6
  end

  local wTaken = takenText(WHITE, takenBuf)
  local bTaken = takenText(BLACK, takenBuf)
  local edge = game:materialEdge(WHITE)
  local tag = ""
  if edge > 0 then tag = "  +" .. edge
  elseif edge < 0 then tag = "  " .. edge end
  line(gc, "W takes: " .. ((wTaken ~= "") and wTaken or "-") .. ((edge > 0) and tag or ""),
    INK_DIM, 9)
  line(gc, "B takes: " .. ((bTaken ~= "") and bTaken or "-") .. ((edge < 0) and tag or ""),
    INK_DIM, 9)

  local last = game:lastMove()
  if last then line(gc, "Last: " .. last.text, INK, 10) end
  line(gc, "Move " .. game.full, INK_DIM, 9)

  if y + 6 <= bottom then
    col(gc, HUD_RULE); gc:drawLine(x, y + 2, x + w, y + 2); y = y + 6
  end

  line(gc, "enter  pick / place", INK_DIM, 9)
  line(gc, "U undo    F flip", INK_DIM, 9)
  line(gc, "esc back  M menu", INK_DIM, 9)
end

-- ---------------------------------------------------------------- overlays --

-- lines: array of { text, dim, marked } -- dim entries blink, as on Snake's
-- panels, and a marked one gets the caret in the gutter.
--
-- `leftAlign` is for the menu. Centring rows whose text changes length as the
-- values cycle makes every row jump sideways when any one of them is altered,
-- which reads as the panel twitching rather than as a setting changing.
local function drawPanel(gc, title, lines, accent, leftAlign)
  gc:setFont("sansserif", "b", 16)
  local titleW = gc:getStringWidth(title)

  gc:setFont("sansserif", "r", 10)
  local maxW = titleW
  for _, l in ipairs(lines) do
    local lw = gc:getStringWidth(l[1])
    if lw > maxW then maxW = lw end
  end

  local gutter = leftAlign and 10 or 0
  maxW = maxW + gutter
  local pad, lineH = 10, 13
  -- Clamp to the window: the handheld is always wide enough, but the computer
  -- software can be resized smaller than the panel's natural size, and the
  -- Nspire clips silently rather than complaining.
  local bw = math.min(maxW + pad * 2, ui.w - 4)
  local bh = math.min(22 + #lines * lineH + pad * 2, ui.h - HUD_H - 4)
  local bx = math.max(2, math.floor((ui.w - bw) / 2))
  local by = math.max(HUD_H + 2, math.floor((ui.h - bh) / 2) + math.floor(HUD_H / 2))

  col(gc, PANEL_BG); gc:fillRect(bx, by, bw, bh)
  col(gc, accent); gc:drawRect(bx, by, bw, bh)

  gc:setFont("sansserif", "b", 16)
  col(gc, accent)
  gc:drawString(title, bx + math.floor((bw - titleW) / 2), by + pad - 2, "top")

  gc:setFont("sansserif", "r", 10)
  local y = by + pad + 20
  local lit = (blink % 16) < 10
  for _, l in ipairs(lines) do
    if l[3] then
      col(gc, accent)
      gc:fillRect(bx + pad, y + 4, 5, 5)
    end
    if l[2] and not lit then col(gc, INK_DIM)
    elseif l[2] or l[3] then col(gc, INK)
    else col(gc, INK_DIM) end
    local tx = leftAlign and (bx + pad + gutter)
      or (bx + math.floor((bw - gc:getStringWidth(l[1])) / 2))
    gc:drawString(l[1], tx, y, "top")
    y = y + lineH
  end
  return bx, by, bw, bh
end

-- The rows that do not apply to the chosen mode read "--" rather than
-- vanishing: a menu that changes shape as you move through it is harder to
-- learn than one that always shows the same four things.
local function menuLines()
  local hot = (menu.mode == 1)
  return {
    { "Players: " .. MODE_NAMES[menu.mode], false, menu.row == 1 },
    { "Level: " .. (hot and "--" or level().name), false, menu.row == 2 },
    { "Play as: " .. (hot and "--" or SIDE_NAME[menu.side]), false, menu.row == 3 },
    { "Turn board: " .. (hot and ONOFF[menu.autoFlip] or "--"), false, menu.row == 4 },
    { "arrows choose    enter starts", true },
  }
end

-- The promotion chooser. Four pieces, drawn the way they will look on the
-- board, because "Q R B N" as bare text next to a board full of discs is a
-- second visual language to learn for no reason.
local function drawPromoPanel(gc)
  local side = game.side
  local cell = math.max(SPRITE_PX + 4, math.min(ui.cell + 6, 28))
  local hint = "arrows pick    enter takes it"
  -- Wide enough for the four pieces *and* for the hint under them, measured
  -- rather than guessed: the hint is the longer of the two at every cell size
  -- the handheld actually uses.
  gc:setFont("sansserif", "r", 9)
  local bw = math.max(cell * 4 + 24, gc:getStringWidth(hint) + 20)
  bw = math.min(bw, ui.w - 4)
  local bh = cell + 46
  local bx = math.max(2, math.floor((ui.w - bw) / 2))
  local by = math.max(HUD_H + 2, math.floor((ui.h - bh) / 2))

  col(gc, PANEL_BG); gc:fillRect(bx, by, bw, bh)
  col(gc, ACCENT); gc:drawRect(bx, by, bw, bh)

  gc:setFont("sansserif", "b", 10)
  local title = "Promote to"
  col(gc, ACCENT)
  gc:drawString(title, bx + math.floor((bw - gc:getStringWidth(title)) / 2), by + 5, "top")

  local sx = bx + math.floor((bw - cell * 4) / 2)
  local sy = by + 21
  for i = 1, 4 do
    local x = sx + (i - 1) * cell
    if i == promo.choice then
      col(gc, ACCENT); gc:fillRect(x, sy, cell, cell)
    end
    -- The same sprites as the board, so there is no second visual language
    -- to learn at the one moment the player has to make a choice.
    drawSprite(gc, Chess.PROMO_PIECES[i], side,
      x + math.floor((cell - SPRITE_PX) / 2), sy + math.floor((cell - SPRITE_PX) / 2))
  end

  gc:setFont("sansserif", "r", 9)
  col(gc, INK_DIM)
  gc:drawString(hint, bx + math.floor((bw - gc:getStringWidth(hint)) / 2),
    sy + cell + 4, "top")
end

local function overText()
  local r = game.result
  if not r then return "GAME OVER", {} end
  if r.kind == "checkmate" then
    return "CHECKMATE", { { SIDE_NAME[r.winner] .. " wins" } }
  elseif r.kind == "stalemate" then
    return "STALEMATE", { { "Draw -- no legal move, no check" } }
  elseif r.kind == "fifty" then
    return "DRAW", { { "Fifty moves without a capture" }, { "or a pawn move" } }
  elseif r.kind == "repetition" then
    return "DRAW", { { "Same position three times" } }
  end
  return "DRAW", { { "Neither side can force mate" } }
end

local function drawOverlay(gc)
  if game.state == "ready" then
    drawPanel(gc, "CHESS", menuLines(), ACCENT, true)
  elseif promo then
    drawPromoPanel(gc)
  elseif game.state == "paused" then
    drawPanel(gc, "PAUSED", {
      { SIDE_NAME[game.side] .. " to move" },
      { "Press enter to resume", true },
    }, ACCENT)
  elseif game:isOver() then
    local title, lines = overText()
    lines[#lines + 1] = { "enter plays again   esc menu", true }
    drawPanel(gc, title, lines, ACCENT)
  end
end

function on.paint(gc)
  col(gc, PAGE); gc:fillRect(0, 0, ui.w, ui.h)
  drawSquares(gc)
  drawHighlights(gc)
  drawPieces(gc)
  drawDests(gc)
  drawCursor(gc)
  drawLabels(gc)
  drawSidebar(gc)
  drawHud(gc)
  drawOverlay(gc)
end
