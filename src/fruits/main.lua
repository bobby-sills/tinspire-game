local function cellX(gx) return ui.bx + (gx - 1) * ui.cell end
local function cellY(gy) return ui.by + (gy - 1) * ui.cell end

-- Where a sprite sits inside its cell.
local function spriteX(gx) return cellX(gx) + ui.pad end
local function spriteY(gy) return cellY(gy) + ui.pad end

-- The cell under a click, or nil.
local function cellAt(px, py)
  local gx = floor((px - ui.bx) / ui.cell) + 1
  local gy = floor((py - ui.by) / ui.cell) + 1
  if Fruit.inside(gx, gy) then return gx, gy end
  return nil
end

-- Called before the first paint, and again on every resize -- which on a
-- handheld means never, but the computer software resizes freely.
function on.resize(w, h)
  ui.w, ui.h = w, h

  -- The hint strip is the first thing to go when the window is short.
  local hintH = (h - HUD_H >= 128) and 14 or 0
  local avail = h - HUD_H - hintH - 4

  -- Size the board once to find out whether a side panel would still fit
  -- beside it, then size it again with the panel's width taken out.
  local cell = floor(min(w - 8, avail) / N)
  local panelW = 0
  if w - (cell * N + 12) >= MIN_PANEL then
    panelW = min(140, w - (cell * N + 12))
    cell = floor(min(w - 12 - panelW, avail) / N)
  end
  if cell < 5 then cell = 5 end

  -- Only ever an integer multiple of the art, never a fractional blow-up: a
  -- 16-pixel sprite stretched to 21 is a smear, and the extra pixels are
  -- better spent on the gutter between fruit, which is what makes a run of
  -- three read as three things rather than one stripe.
  local k = floor((cell - 4) / ART_SIZE)
  ui.sprite = (k >= 1) and (ART_SIZE * k) or max(3, cell - 2)
  ui.pad = floor((cell - ui.sprite) / 2)

  ui.cell = cell
  ui.side = cell * N
  ui.panelW = panelW
  ui.bx = max(2, floor((w - panelW - ui.side) / 2))
  ui.by = max(HUD_H, HUD_H + floor((h - HUD_H - hintH - ui.side) / 2))

  ui.panelX = ui.bx + ui.side + 6
  ui.panelH = ui.side
  if ui.panelX + panelW > w - 2 then panelW = max(0, w - 2 - ui.panelX) end
  ui.panelW = (panelW >= MIN_PANEL) and panelW or 0

  ui.hintY = ui.by + ui.side + 3
  ui.hint = hintH > 0 and (ui.hintY + 13 <= h)

  platform.window:invalidate()
end

