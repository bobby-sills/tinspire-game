-- An arrow with a fruit picked up is the swap itself: one keypress, no
-- confirm. Without a selection it just walks the cursor.
local function steer(dir)
  local d = DELTA[dir]
  if not d then return end

  beginRound()
  if board.state ~= "playing" or board.phase ~= "idle" then return end

  if sel then
    local tx, ty = sel.x + d[1], sel.y + d[2]
    if Fruit.inside(tx, ty) then
      board:swap(sel.x, sel.y, tx, ty)
      cur.x, cur.y = tx, ty
      sel = nil
    end
    return
  end

  local nx, ny = cur.x + d[1], cur.y + d[2]
  if Fruit.inside(nx, ny) then cur.x, cur.y = nx, ny end
end

function on.arrowKey(key)
  stir(2)
  steer(key)
  platform.window:invalidate()
end

function on.enterKey()
  stir(3)
  confirm()
  platform.window:invalidate()
end

function on.escapeKey()
  stir(5)
  if board.state == "playing" then
    board:pause()
  elseif board.state == "paused" then
    board:resume()
  end
  platform.window:invalidate()
end

-- The keypad reads 7 8 9 / 4 5 6 / 1 2 3, so 2/4/6/8 are the arrows, the same
-- way every other game in this repo takes them.
local CHAR_DIRS = {
  w = "up",    ["8"] = "up",
  s = "down",  ["2"] = "down",
  a = "left",  ["4"] = "left",
  d = "right", ["6"] = "right",
}

function on.charIn(ch)
  ch = string.lower(ch or "")
  stir(7)

  local dir = CHAR_DIRS[ch]
  if dir then
    steer(dir)
  elseif ch == " " or ch == "5" then
    confirm()
  elseif ch == "p" then
    if board.state == "playing" then board:pause()
    elseif board.state == "paused" then board:resume() end
  elseif ch == "r" then
    newRound()
    board:start()
  elseif ch == "h" then
    board:showHint()   -- the deliberate one, and it costs
  end

  platform.window:invalidate()
end

-- Click to pick up, click a neighbour to swap. Clicking anywhere else moves
-- the pick-up rather than refusing, which is what a player expects from a
-- touchpad they cannot aim precisely with.
function on.mouseDown(px, py)
  stir(11)
  local s = board.state

  if s ~= "playing" then
    confirm()
    platform.window:invalidate()
    return
  end

  local gx, gy = cellAt(px, py)
  if gx and board.phase == "idle" then
    cur.x, cur.y = gx, gy
    if sel and Fruit.adjacent(sel.x, sel.y, gx, gy) then
      board:swap(sel.x, sel.y, gx, gy)
      sel = nil
    elseif sel and sel.x == gx and sel.y == gy then
      sel = nil
    else
      sel = { x = gx, y = gy }
    end
  end
  platform.window:invalidate()
end

-- ----------------------------------------------------------------- drawing --

-- Which cells must NOT be drawn sitting on their own square, because they are
-- in flight and will be drawn tweened instead. Rebuilt per frame; 64 booleans
-- is cheaper than any bookkeeping that would avoid it.
local moving = {}

local function markMoving()
  for i = 1, Fruit.CELLS do moving[i] = false end
  local m = board.motion
  for i = 1, #m do
    local e = m[i]
    local x = e.x
    local y = e.toY or e.y
    if Fruit.inside(x, y) then moving[(y - 1) * N + x] = true end
  end
end

local function drawCells(gc)
  col(gc, BOARD_BG)
  gc:fillRect(ui.bx, ui.by, ui.side, ui.side)

  -- A checker, so a row of eight cells reads as eight cells even where three
  -- neighbours are the same fruit.
  for y = 1, N do
    for x = 1, N do
      col(gc, ((x + y) % 2 == 0) and CELL_A or CELL_B)
      gc:fillRect(cellX(x), cellY(y), ui.cell, ui.cell)
    end
  end
end

-- The white outline of a fruit's own shape: the one-pixel halo around its
-- silhouette, emitted by tools/fruitart.py and scaled exactly as the sprite
-- is, so the two stay registered at every throb size.
local function drawHalo(gc, kind, px, py, size)
  local a = ART[kind]
  if not a or not a.halo or #a.halo == 0 then return end
  col(gc, HALO)
  local h = a.halo
  for i = 1, #h, 4 do
    local x, y, w, hh = byte(h, i, i + 3)
    -- Stored in an 18x18 frame shifted by +1, because the outline of a sprite
    -- that reaches the edge of its own box falls outside that box.
    x, y = x - ART_OFFSET - 1, y - ART_OFFSET - 1
    w, hh = w - ART_OFFSET, hh - ART_OFFSET
    local x0 = floor(x * size / ART_SIZE)
    local y0 = floor(y * size / ART_SIZE)
    local x1 = floor((x + w) * size / ART_SIZE)
    local y1 = floor((y + hh) * size / ART_SIZE)
    gc:fillRect(px + x0, py + y0, max(1, x1 - x0), max(1, y1 - y0))
  end
end

-- A power fruit: the ordinary sprite, with its outline behind it on the half
-- of the cycle the flash is on.
local function drawPower(gc, kind, x, y, px, py)
  if flashOn then drawHalo(gc, kind, px, py, ui.sprite) end
  drawFruit(gc, kind, px, py, ui.sprite)
end

-- The fruit that are sitting still. During `clear` the matched ones are still
-- on the board -- that is the phase's whole job, to show them going -- so they
-- are drawn shrinking over a pale backing instead of being skipped.
local function drawStatic(gc)
  local bursting = (board.phase == "clear")
  local p = bursting and board:phaseProgress() or 0
  local shrunk = max(2, floor(ui.sprite * (1 - p * 0.75)))
  local marked = board.marked

  for y = 1, N do
    for x = 1, N do
      local i = (y - 1) * N + x
      if not moving[i] then
        local k = board.cells[i]
        if k and k ~= 0 then
          if bursting and marked[i] then
            -- Shrinking, over nothing. An earlier version put a pale rect
            -- behind a bursting fruit to say "this one is going"; at cell size
            -- and near-white it read as a rendering fault rather than a cue,
            -- and the shrink says it on its own.
            local off = floor((ui.cell - shrunk) / 2)
            drawFruit(gc, k, cellX(x) + off, cellY(y) + off, shrunk)
          else
            -- A picked-up fruit rides a little high, so the pick-up reads even
            -- where the cursor ring is sitting on top of it. Never more than
            -- the gutter, or it would climb out of its own cell.
            local lift = (sel and sel.x == x and sel.y == y) and min(2, ui.pad) or 0
            local px, py = spriteX(x), spriteY(y) - lift
            if board.special[i] then
              drawPower(gc, k, x, y, px, py)
            else
              drawFruit(gc, k, px, py, ui.sprite)
            end
          end
        end
      end
    end
  end
end

-- Everything in flight, at its interpolated position. Falling fruit come from
-- above the board and are deliberately allowed to overflow upward: on.paint
-- repaints the HUD bar afterwards, which covers the overflow for nothing,
-- rather than paying to clip every rect.
local function drawMoving(gc)
  local m = board.motion
  if #m == 0 then return end

  local p = board:phaseProgress()
  for i = 1, #m do
    local e = m[i]
    local fx = e.fromX or e.x
    local fy = e.fromY
    local tx = e.toX or e.x
    local ty = e.toY
    local px = spriteX(fx) + (spriteX(tx) - spriteX(fx)) * p
    local py = spriteY(fy) + (spriteY(ty) - spriteY(fy)) * p
    drawFruit(gc, e.kind, floor(px + 0.5), floor(py + 0.5), ui.sprite)
  end
end

local function outline(gc, c, x, y, inset)
  col(gc, c)
  gc:drawRect(cellX(x) + inset, cellY(y) + inset,
              ui.cell - 1 - inset * 2, ui.cell - 1 - inset * 2)
end

-- One ring on the cursor's cell, not two stacked.
--
-- Picking a fruit up never moves the cursor off it -- `confirm` selects the
-- cell the cursor is already on, and an arrow with something picked up
-- performs the swap rather than steering -- so the cursor and the pick-up are
-- always the same cell. Two rings there is two outlines describing one thing,
-- which reads as clutter rather than as information. So the ring changes
-- colour instead, and the fruit under it lifts a couple of pixels: one mark,
-- two ways of telling what state it is in. tests/fruits/ui.lua pins the
-- premise, so this stays honest if the input handling ever changes.
local function drawMarkers(gc)
  if board.state ~= "playing" and board.state ~= "paused" then return end

  local h = board.hint
  if h then
    outline(gc, HINT, h.x1, h.y1, 0)
    outline(gc, HINT, h.x2, h.y2, 0)
  end
  outline(gc, sel and SELECT or CURSOR, cur.x, cur.y, 0)
end

-- Drops fields rather than assume the whole line fits: a long game plus a
-- narrow window is exactly when the Nspire would clip it without a word.
local function drawHud(gc)
  col(gc, HUD_BG)
  gc:fillRect(0, 0, ui.w, ui.by)
  col(gc, HUD_RULE)
  gc:drawLine(0, ui.by - 1, ui.w, ui.by - 1)

  gc:setFont("sansserif", "b", 12)
  local titleW = gc:getStringWidth("Fruits")
  local titleFits = titleW + 12 < ui.w
  if titleFits then
    col(gc, GOLD)
    gc:drawString("Fruits", 5, floor((ui.by - 16) / 2), "top")
  end

  -- The side panel already carries the numbers. Repeating them here would
  -- just be two of everything, so the bar keeps the score only when there is
  -- no panel to put it in.
  if ui.panelW > 0 then return end

  gc:setFont("sansserif", "r", 10)
  local stats, statsX
  for _, candidate in ipairs({
    "Score " .. board.score .. "   Best " .. board.best .. "   Moves " .. board.moves,
    "Score " .. board.score .. "   Best " .. board.best,
    "Score " .. board.score,
  }) do
    stats = candidate
    statsX = ui.w - gc:getStringWidth(candidate) - 6
    if not titleFits or statsX > titleW + 12 then break end
  end

  col(gc, TEXT)
  gc:drawString(stats, max(3, statsX), floor((ui.by - 14) / 2), "top")
end

-- One "LABEL      value" row, returning the y the next row starts at.
--
-- The height comes from gc:getStringHeight and not from a constant. That is
-- not fussiness: this panel shipped with its row heights written down as
-- numbers that were right for the font the MOCK measures with, and on the
-- calculator -- whose font is taller -- the rule ran through the SCORE text
-- and the level bar sat on top of the word LEVEL. Nothing here may assume how
-- tall a line is.
local function panelRow(gc, label, value, x, y, w, accent)
  gc:setFont("sansserif", "r", 9)
  local h = gc:getStringHeight(label)
  col(gc, DIM)
  gc:drawString(label, x, y, "top")

  gc:setFont("sansserif", "b", 11)
  h = max(h, gc:getStringHeight(value))
  col(gc, accent or TEXT)
  gc:drawString(value, x + max(0, w - gc:getStringWidth(value)), y, "top")
  return y + h + 2
end

-- How tall a plain row is, measured, so the panel can budget for the rows it
-- has not drawn yet before deciding how big the score may be.
local function panelRowHeight(gc)
  gc:setFont("sansserif", "r", 9)
  local h = gc:getStringHeight("0")
  gc:setFont("sansserif", "b", 11)
  return max(h, gc:getStringHeight("0")) + 2
end

local BAR_H = 5

local function drawPanel(gc)
  if ui.panelW <= 0 then return end
  local x, y, w = ui.panelX, ui.by, ui.panelW
  col(gc, PANEL_BG)
  gc:fillRect(x, y, w, ui.panelH)

  local ix, iw = x + 9, w - 18
  local pad = 8
  local cy = y + pad
  local bottom = y + ui.panelH - pad

  local rowH = panelRowHeight(gc)
  -- What the rest of the panel needs: four rows, the level bar, and the rule.
  -- The score gets whatever is left, which is why it is measured first.
  local below = rowH * 4 + BAR_H + 4 + 8

  gc:setFont("sansserif", "r", 9)
  col(gc, DIM)
  gc:drawString("SCORE", ix, cy, "top")
  cy = cy + gc:getStringHeight("SCORE") + 1

  -- Step the score down through the sizes rather than let it run off the panel
  -- or into the rows underneath. Six figures at 24pt does not fit, and the
  -- Nspire would clip it without a word.
  local sc = tostring(board.score)
  local room = bottom - below - cy
  gc:setFont("sansserif", "b", 12)
  for _, size in ipairs({ 24, 16, 12 }) do
    gc:setFont("sansserif", "b", size)
    if gc:getStringWidth(sc) <= iw and gc:getStringHeight(sc) <= room then break end
  end
  col(gc, GOLD)
  gc:drawString(sc, ix + max(0, iw - gc:getStringWidth(sc)), cy, "top")
  cy = cy + gc:getStringHeight(sc) + 4

  col(gc, HUD_RULE)
  gc:drawLine(ix, cy, ix + iw, cy)
  cy = cy + 5

  -- Each row is drawn only if it fits. On a short panel the bottom ones drop
  -- off rather than piling up on each other.
  local function row(label, value, accent)
    if cy + rowH > bottom then return false end
    cy = panelRow(gc, label, value, ix, cy, iw, accent)
    return true
  end

  if row("LEVEL", tostring(board.level), board.leveledUp and HINT or nil) then
    -- The bar goes on its own line UNDER the level row -- never overlapping
    -- it. Drawn from the game's own 0..1 rather than from the counts, so the
    -- panel cannot disagree with the rule about when a level ends.
    if cy + BAR_H <= bottom then
      col(gc, BAR_BG)
      gc:fillRect(ix, cy, iw, BAR_H)
      local filled = floor(iw * board:levelProgress() + 0.5)
      if filled > 0 then
        col(gc, BAR_FILL)
        gc:fillRect(ix, cy, filled, BAR_H)
      end
      cy = cy + BAR_H + 4
    end
  end

  row("BEST", tostring(board.best))
  row("MOVES", tostring(board.moves))

  -- The chain multiplier only means anything while a cascade is running, so it
  -- shows live then and the round's best otherwise.
  local live = board.chain and board.chain > 1
  row(live and "CHAIN" or "BEST CHAIN",
      "x" .. Fruit.chainMult(live and board.chain or board.bestChain),
      live and HINT or nil)

  if board.lastGain and board.lastGain > 0 and board:busy() then
    gc:setFont("sansserif", "b", 16)
    if cy + gc:getStringHeight("0") <= bottom then
      col(gc, GOLD)
      local t = "+" .. board.lastGain
      gc:drawString(t, ix + max(0, iw - gc:getStringWidth(t)), cy + 2, "top")
    end
  end
end

local function drawHint(gc)
  if not ui.hint then return end
  gc:setFont("sansserif", "r", 9)
  col(gc, DIM)
  for _, text in ipairs({
    "Arrows move   enter picks up   arrow swaps   H hint   R restart",
    "Arrows move   enter picks up   H hint   R restart",
    "enter picks up   H hint   R restart",
    "H hint   R restart",
  }) do
    local w = gc:getStringWidth(text)
    if w <= ui.w - 8 then
      gc:drawString(text, floor((ui.w - w) / 2), ui.hintY, "top")
      return
    end
  end
end

-- lines: array of { text, highlight }. The same overlay shape the other games
-- use, clamped to the window because the computer software can be resized
-- smaller than the panel's natural size and the Nspire clips silently.
local function overlay(gc, title, lines, accent)
  gc:setFont("sansserif", "b", 16)
  local titleW = gc:getStringWidth(title)

  gc:setFont("sansserif", "r", 10)
  local maxW = titleW
  for _, l in ipairs(lines) do
    maxW = max(maxW, gc:getStringWidth(l[1]))
  end

  local pad, lineH = 12, 14
  local bw = min(maxW + pad * 2, ui.w - 4)
  local bh = min(24 + #lines * lineH + pad * 2, ui.h - 4)
  local bx = max(2, floor((ui.w - bw) / 2))
  local by = max(2, floor((ui.h - bh) / 2))

  col(gc, PANEL_BG)
  gc:fillRect(bx, by, bw, bh)
  col(gc, accent)
  gc:drawRect(bx, by, bw, bh)

  gc:setFont("sansserif", "b", 16)
  col(gc, accent)
  gc:drawString(title, bx + floor((bw - titleW) / 2), by + pad - 2, "top")

  gc:setFont("sansserif", "r", 10)
  local y = by + pad + 22
  for _, l in ipairs(lines) do
    col(gc, l[2] and TEXT or DIM)
    gc:drawString(l[1], bx + floor((bw - gc:getStringWidth(l[1])) / 2), y, "top")
    y = y + lineH
  end
end

-- True while a modal panel is up. The side panel is skipped then: the overlay
-- is centred on the window and the panel is not, so the two collide, and the
-- overlay repeats the numbers that matter anyway.
local function overlayUp()
  local s = board.state
  return s == "ready" or s == "paused" or s == "over"
end

local function drawOverlay(gc)
  local s = board.state
  if s == "ready" then
    overlay(gc, "FRUITS", {
      { "Swap two neighbours to line up three" },
      { "Arrows or 2/4/6/8 move   enter picks up" },
      { "With one picked up, an arrow swaps it" },
      { "Chains multiply; no move left ends it" },
      { "Press enter to play", true },
    }, GOLD)
  elseif s == "paused" then
    overlay(gc, "PAUSED", {
      { "Score " .. board.score .. "     Best " .. board.best },
      { "Press enter to resume", true },
    }, GOLD)
  elseif s == "over" then
    overlay(gc, "NO MOVES LEFT", {
      { "Score " .. board.score .. "     Best " .. board.best },
      { board.cleared .. " fruit cleared in " .. board.moves .. " moves" },
      { "Longest chain x" .. Fruit.chainMult(board.bestChain) },
      { "Press enter for a new board", true },
    }, RED)
  end
end

function on.paint(gc)
  col(gc, PAGE_BG)
  gc:fillRect(0, 0, ui.w, ui.h)

  markMoving()
  drawCells(gc)
  drawStatic(gc)
  drawMoving(gc)

  -- After the fruit, deliberately: newcomers fall in from above the board and
  -- these two cover the overflow.
  drawHud(gc)
  if not overlayUp() then drawPanel(gc) end

  drawMarkers(gc)
  drawHint(gc)
  drawOverlay(gc)
end
