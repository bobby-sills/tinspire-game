-- imageprobe2.lua -- the same question as tools/probe/imageprobe.lua, asked
-- again with the real answer in hand.
--
-- The first probe guessed twelve header layouts and none of them painted. The
-- format is documented at wiki.inspired-lua.org/TI.Image, which cannot be
-- fetched from this container but was supplied by hand: a 20-byte
-- little-endian header --
--
--   0  u32  pixel width
--   4  u32  pixel height
--   8  u8   alignment (0)
--   9  u8   flags (0)
--   10 u16  padding (0)
--   12 u32  bytes between raster lines (2 * width)
--   16 u16  bits per pixel (16)
--   18 u16  planes (1)
--
-- -- followed by 16-bit little-endian pixels laid out A RRRRR GGGGG BBBBB,
-- alpha in the TOP bit: 1 draws the pixel, 0 leaves it transparent. Note that
-- is RGB555 with an alpha bit, not the RGB565 the first probe assumed, and the
-- header is 20 bytes rather than the 16 it guessed. Either mistake alone
-- paints nothing.
--
-- The wiki also says image.new takes this string only at apilevel < 2.3; from
-- 2.3 (OS 3.6) it wants a TI.ResourceHandle built by TI's own SDK instead.
-- This document declares 2.0, so it should get the string path. Whether a CX
-- II on a current OS still honours that is exactly what candidate 1 is for:
-- it is the wiki's own two-by-two white example, copied byte for byte, so if
-- that one does not paint then nothing built this way will and the fillRect
-- sprites stay.
--
-- Build:  make probe2   ->  ImageProbe2.tns

