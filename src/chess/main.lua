-- The pieces as TI.Image objects, indexed [type][side], or nil if this runtime
-- will not make them.
--
-- gc:drawImage draws a whole piece in one call where the runs above take about
-- thirty, which is the difference between 32 calls for a full board and ~940.
-- Chess repaints on a key rather than on a timer, so that is a per-keypress
-- cost -- but it is the cost of every keypress, and the arrow keys move a
-- cursor one square at a time.
--
-- The care this needs: image.new's string form is documented only for
-- apilevel < 2.3 (from 2.3 it wants a TI.ResourceHandle built by TI's own
-- SDK), and it was verified on one CX II with tools/probe/imageprobe2.lua --
-- one calculator, one OS. So it is built inside a pcall and the whole thing is
-- all-or-nothing: if any piece fails to build, every piece falls back to the
-- runs, because half a board in one encoding and half in the other would look
-- like a bug rather than a fallback. The runs are not a lesser picture --
-- tools/sprites.py checks the two encodings against the art and against each
-- other, pixel for pixel -- they are only slower.
local sprites = (function()
  if type(image) ~= "table" or type(image.new) ~= "function" then return nil end
  local out = {}
  for t = 1, #SPRITES do
    out[t] = {}
    for side = 1, 2 do
      local built, img = pcall(image.new, SPRITES[t].img[side])
      if not built or not img then return nil end
      out[t][side] = img
    end
  end
  return out
end)()

