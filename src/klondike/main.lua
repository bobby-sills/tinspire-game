-- main.lua -- TI-Nspire presentation layer: drawing, input, timing.
--
-- Rules live in src/klondike/game.lua. `platform.apilevel` is emitted as the
-- first line of the bundle by tools/bundle.py, so it is intentionally absent
-- here.
--
-- When bundled, `Klondike` is already a local from the inlined module; the
-- `Klondike or require` form below also lets this file load under a desktop
-- Lua.
local Klondike = Klondike or require("game")

-- ------------------------------------------------------------------ tuning --
-- Klondike is strictly turn-based, so there is no game loop and no animation:
-- every repaint is caused by a key. The timer runs only so that idle time on
-- the title screen can be counted into the seed -- see newSeed.
local BASE_TICK = 0.05

-- The fan. A column can hold six face-down cards under a full king-to-ace run
-- of thirteen, and sizing every column for that worst case would force about
-- six pixels on all of them and ruin the common case. So the steps are worked
-- out per column at paint time from what that column actually holds, and only
-- squeezed when that column needs it.
--
-- FAN_UP_MAX shows the whole corner index, rank and suit. FAN_UP_MIN still
-- shows the rank glyph, which ends at row 7 of the art. Face-down cards are
-- identical backs and carry nothing, so they are squeezed first and hardest.
local FAN_UP_MAX,   FAN_UP_MIN   = 16, 9
local FAN_DOWN_MAX, FAN_DOWN_MIN = 7, 2

-- Draw-3 spreads its three turned cards to the right, into the gap the grid
-- leaves between the waste and the foundations. 13px shows each card's corner
-- index, which is all there is to see: only the last one is playable.
local WASTE_FAN = 13

local HUD_H    = 18   -- status bar across the top
local MARGIN   = 4
local ROW_GAP  = 4    -- between the top row of piles and the tableau
local GAP_MIN, GAP_MAX = 4, 16   -- between columns
-- ---------------------------------------------------------------------------

