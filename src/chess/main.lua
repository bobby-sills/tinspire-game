-- Called before the first paint, and again if the window is resized -- which
-- on a handheld means never, but the computer software can resize freely.
-- The board is always 8x8, so a resize only ever changes the scale: unlike
-- Snake, there is no reason for it to disturb a game in progress.
function on.resize(w, h)
  ui.w, ui.h = w, h

  -- Try the full layout -- coordinates down two edges, sidebar to the right --
  -- and give each of them up in turn if the squares would get too small to
  -- play on. The handheld always affords all of it; the computer software can
  -- be dragged smaller than any of it.
  --
  -- The reserves include the moulded rim on all four sides, so the board plus
  -- its frame is what gets fitted, not the squares alone.
  local function fit(labels, sidebar)
    local reserveW = RIM * 2 + 2 + (labels and LABEL or 0)
      + (sidebar and (GAP + SIDEBAR_MIN + MARGIN) or 0)
    local reserveH = HUD_H + RIM * 2 + 2 + (labels and LABEL or 0)
    local cell = math.floor(math.min((w - reserveW) / 8, (h - reserveH) / 8))
    if cell > CELL_MAX then cell = CELL_MAX end
    return cell, reserveW, reserveH
  end

  local labels, sidebar = true, true
  local cell = fit(labels, sidebar)
  if cell < LABEL_CELL then labels = false; cell = fit(labels, sidebar) end
  if cell < CELL_MIN then sidebar = false; cell = fit(labels, sidebar) end
  if cell < CELL_MIN then
    -- Below the smallest playable board, drop everything else and take
    -- whatever squares are left. Shrinking past the minimum beats painting
    -- over the edge: the Nspire clips silently, so half a board that is
    -- invisible is worse than a whole one that is too small to enjoy.
    labels, sidebar = false, false
    cell = CELL_MIN
    local hard = math.floor(math.min((w - RIM * 2 - 2) / 8, (h - HUD_H - RIM * 2 - 2) / 8))
    if cell > hard then cell = hard end
    if cell < 1 then cell = 1 end
  end

  local _, reserveW, reserveH = fit(labels, sidebar)
  ui.cell, ui.labels = cell, labels
  ui.board = cell * 8
  ui.bx = RIM + 1 + (labels and LABEL or 0)
  ui.by = HUD_H + RIM + 1
    + math.max(0, math.floor((h - reserveH - ui.board) / 2))

  ui.sx = ui.bx + ui.board + GAP
  ui.sw = w - ui.sx - MARGIN
  ui.sidebar = sidebar and ui.sw >= SIDEBAR_MIN
  if not ui.sidebar then
    -- No sidebar to make room for, so centre what is left.
    ui.bx = math.max(RIM + 1, math.floor((w - ui.board) / 2))
    ui.sw = 0
  end

  -- The sprites are a fixed 16x16 and there is no scaling in this sandbox, so
  -- they are drawn at native size centred in the square. Anything smaller than
  -- that falls back to letters rather than to a cropped piece.
  ui.sprites = cell >= SPRITE_PX
  ui.spriteInset = math.floor((cell - SPRITE_PX) / 2)

  -- The largest supported font whose cap height still leaves a ring of disc
  -- visible around it. Sizes are chosen from the list the OS actually has,
  -- never computed, because anything else is silently rejected. Only the
  -- letter fallback uses this.
  ui.pieceSize = FONT_SIZES[#FONT_SIZES]
  for _, sz in ipairs(FONT_SIZES) do
    if sz <= cell - 5 then ui.pieceSize = sz; break end
  end

  platform.window:invalidate()
end

timer.start(BASE_TICK)

function on.timer()
  blink = blink + 1
  local dirty = false

  if game.state == "ready" or game.state == "paused" then
    entropy = entropy + 1
    if blink % 8 == 0 then dirty = true end

  elseif phase == "thinking" then
    thinkTicks = thinkTicks + 1
    local mv = ai:think(TICK_NODES)

    -- The turn is capped in ticks, not in nodes, because how many nodes fit
    -- in a tick depends on a machine this code cannot measure. Whatever depth
    -- finished by now is the one that plays.
    if not mv and thinkTicks >= level().thinkTicks then
      mv = ai:stop()
    end

    -- An instant answer -- a forced mate, or a one-move game -- would
    -- otherwise flash past with the board apparently moving on its own, so
    -- hold the indicator up for a few ticks either way.
    if mv and thinkTicks >= MIN_THINK_TICKS then
      phase = "idle"
      if not playMove(mv) then afterMove() end
    elseif not mv and ai.done then
      -- The search says there is no move: the game is already over, and
      -- updateResult will have said so. Do not spin.
      phase = "idle"
    end
    dirty = true

  elseif game:isOver() then
    if blink % 8 == 0 then dirty = true end
  end

  if dirty then platform.window:invalidate() end
end

function on.deactivate()
  -- Losing focus mid-search would leave the bot holding a half-finished
  -- search across an unknown gap in time; pausing throws it away cleanly.
  if game.state == "playing" then togglePause() end
  platform.window:invalidate()
end

