  gc:fillRect(x + 1, y + 1, CARD_W - 2, CARD_H - 2)
  col(gc, SLOT_LINE)
  gc:fillRect(x + 1, y, CARD_W - 2, 1)
  gc:fillRect(x + 1, y + CARD_H - 1, CARD_W - 2, 1)
  gc:fillRect(x, y + 1, 1, CARD_H - 2)
  gc:fillRect(x + CARD_W - 1, y + 1, 1, CARD_H - 2)

  if suit then
    local pip = CARD_PIPS[suit]
    local pw, ph, s = pip[1], pip[2], pip[4]
    local px = x + math.floor((CARD_W - pw) / 2)
    local py = y + math.floor((CARD_H - ph) / 2)
    col(gc, CARD_INK[pip[3]])
    for j = 1, #s, 3 do
      gc:fillRect(px + string.byte(s, j + 1) - CARD_PACK,
                  py + string.byte(s, j) - CARD_PACK,
                  string.byte(s, j + 2) - CARD_PACK, 1)
    end
  end
end

-- A ring drawn around a pile or a card. Four rects rather than drawRect,
-- because a two-pixel ring reads at this size and a one-pixel one does not.
local function outline(gc, x, y, w, h, c, thickness)
  local t = thickness or 2
  col(gc, c)
  gc:fillRect(x, y, w, t)
  gc:fillRect(x, y + h - t, w, t)
  gc:fillRect(x, y + t, t, h - 2 * t)
  gc:fillRect(x + w - t, y + t, t, h - 2 * t)
end

-- ------------------------------------------------------------- selection --
--
-- Two-stage, as in chess: left and right move between piles, up and down move
-- within a column's face-up cards -- a player can pick up a run starting
-- anywhere in it, so the cursor has to be able to land anywhere in it. Enter
-- picks up, enter again drops, escape cancels.

local function selMoves(sel)
  if not sel then return {} end
  if sel.where == "tab" then
    if (sel.i or 0) < 1 then return {} end
    return game:movesFrom("tab", sel.a, sel.i)
  elseif sel.where == "waste" then
    return game:movesFrom("waste")
  elseif sel.where == "found" then
    return game:movesFrom("found", sel.a)
  elseif sel.where == "stock" then
    return game:movesFrom("stock")
  end
  return {}
end

local function destKey(m)
  if m.k == "wf" or m.k == "tf" then return "found:" .. m.f end
  if m.k == "wt" or m.k == "tt" or m.k == "ft" then return "tab:" .. m.t end
  return nil
end

-- Every pile the current selection can legally reach. Computed by filtering
-- the rules' own move list rather than by asking a second time in the drawing
-- code, so a highlighted destination and an accepted move cannot disagree --
-- which on a screen this size is the difference between playing and guessing.
local function destSet(sel)
  local d = {}
  for _, m in ipairs(selMoves(sel)) do
    local k = destKey(m)
    if k then d[k] = true end
  end
  return d
end

local function pileKey(sel)
  if not sel then return nil end
  if sel.where == "found" then return "found:" .. sel.a end
  if sel.where == "tab" then return "tab:" .. sel.a end
  return sel.where
end

local function findMove(from, to)
  local want = pileKey(to)
  for _, m in ipairs(selMoves(from)) do
    if destKey(m) == want then return m end
  end
  return nil
end

local function nearestRow1(c)
  local best, bestD = 1, 99
  for k = 1, #ROW1_SLOT do
    local d = math.abs(ROW1_SLOT[k] - c)
    if d < bestD then best, bestD = k, d end
  end
  return best
end

local function row1Index(sel)
  if sel.where == "stock" then return 1 end
  if sel.where == "waste" then return 2 end
  if sel.where == "found" then return 2 + sel.a end
  return nil
end

local function setRow1(k)
  if k < 1 then k = #ROW1_SLOT elseif k > #ROW1_SLOT then k = 1 end
  if k == 1 then cur = { where = "stock" }
  elseif k == 2 then cur = { where = "waste" }
  else cur = { where = "found", a = k - 2 } end
end

local function enterColumn(c)
  cur = { where = "tab", a = c, i = #game.tab[c] }
end

local function navigate(key)
  if cur.where == "tab" then
    if key == "left" then
      enterColumn((cur.a == 1) and COLUMNS or cur.a - 1)
    elseif key == "right" then
      enterColumn((cur.a == COLUMNS) and 1 or cur.a + 1)
    elseif key == "up" then
      -- Walk up the face-up run first; the top of it is the way out.
      if cur.i > game.down[cur.a] + 1 then
        cur.i = cur.i - 1
      else
        setRow1(nearestRow1(cur.a))
      end
    elseif key == "down" then
      if cur.i < #game.tab[cur.a] then cur.i = cur.i + 1 end
    end
  else
    local k = row1Index(cur)
    if key == "left" then setRow1(k - 1)
    elseif key == "right" then setRow1(k + 1)
    elseif key == "down" then enterColumn(row1Slot(k))
    end
  end
end

-- ------------------------------------------------------------------ play --

local function afterMove()
  if game.safeAuto then game:runSafeAuto() end
  if game:isWon() then state = "won" end
  -- The cursor may be pointing past the end of a column that just shrank.
  if cur.where == "tab" then
    local n = #game.tab[cur.a]
    if cur.i > n then cur.i = n end
    if cur.i < game.down[cur.a] + 1 then cur.i = n end
  end
end

local function doMove(m)
  if not game:play(m) then return false end
  held = nil
  message = nil
  afterMove()
  return true
end

local function activate()
  if state ~= "playing" then return end

  if held then
    local m = findMove(held, cur)
    if m then
      doMove(m)
    elseif pileKey(held) == pileKey(cur) then
      held = nil                      -- putting it back where it came from
    else
      held = nil                      -- not a legal target: pick up here instead
      if #selMoves(cur) > 0 then held = { where = cur.where, a = cur.a, i = cur.i } end
    end
    return
  end

  -- The stock has no "pick up": there is only one thing you can do to it.
  if cur.where == "stock" then
    local ms = selMoves(cur)
    if ms[1] then doMove(ms[1]) else message = "no passes left" end
    return
  end

  if #selMoves(cur) > 0 then
    held = { where = cur.where, a = cur.a, i = cur.i }
  else
    message = "nowhere to go"
  end
end

local function undoMove()
  if state == "won" then state = "playing" end
  held = nil
  if game:canUndo() then
    game:undo()
    message = nil
    if cur.where == "tab" then
      local n = #game.tab[cur.a]
      if cur.i > n then cur.i = n end
    end
  else
    message = "nothing to undo"
  end
end

-- ---------------------------------------------------------------- input --

local MENU_ROWS = {
  { label = "Draw",  key = "draw",   opts = { "one card", "three cards" } },
  { label = "Stock", key = "passes", opts = { "unlimited passes", "three passes" } },
  { label = "Safe cards", key = "auto", opts = { "stay put", "go up by themselves" } },
}

local function menuKey(key)
  if key == "up" then
    menu.row = (menu.row == 1) and #MENU_ROWS or menu.row - 1
  elseif key == "down" then
    menu.row = (menu.row == #MENU_ROWS) and 1 or menu.row + 1
  elseif key == "left" or key == "right" then
    local r = MENU_ROWS[menu.row]
    menu[r.key] = (menu[r.key] == 1) and 2 or 1
  end
end

function on.arrowKey(key)
  if state == "menu" then
    menuKey(key)
  elseif state == "playing" then
    navigate(key)
  end
  platform.window:invalidate()
end

function on.enterKey()
  if state == "menu" then
    startGame()
  elseif state == "paused" then
    state = "playing"
  elseif state == "won" then
    startGame()
  else
    activate()
  end
  platform.window:invalidate()
end

function on.escapeKey()
  if state == "playing" then
    if held then held = nil else state = "paused" end
  elseif state == "paused" then
    state = "playing"
  end
  platform.window:invalidate()
end

function on.backspaceKey()
  if state == "playing" or state == "won" then undoMove() end
  platform.window:invalidate()
end

function on.charIn(ch)
  ch = string.lower(ch or "")

  if ch == "m" then
    state = "menu"
  elseif state == "menu" then
    if ch == " " then startGame() end
  elseif ch == "u" then
    undoMove()
  elseif ch == "r" then
    startGame(game.seed)              -- the same deal again, from the top
  elseif ch == "n" then
    startGame()
  elseif ch == "p" then
    if state == "playing" then state = "paused"
    elseif state == "paused" then state = "playing" end
  elseif ch == " " then
    if state == "paused" or state == "won" then on.enterKey() else activate() end
  end

  platform.window:invalidate()
end

-- Clicking picks the card or pile under the point, then does what enter would
-- do with it: with nothing held that is a pick-up, and with a run held it is a
-- drop, so a whole move is two clicks.
local function hit(x, y)
  if y >= ui.topY and y < ui.topY + CARD_H then
    for k = 1, #ROW1_SLOT do
      local sx = slotX(ROW1_SLOT[k])
      if x >= sx and x < sx + CARD_W then
        if k == 1 then return { where = "stock" } end
        if k == 2 then return { where = "waste" } end
        return { where = "found", a = k - 2 }
      end
    end
    -- The hole beside the waste is where the draw-3 spread lands.
    local wx = slotX(2)
    if x >= wx and x < slotX(4) and #game.waste > 0 then return { where = "waste" } end
  elseif y >= ui.tabY then
    for c = 1, COLUMNS do
      local sx = slotX(c)
      if x >= sx and x < sx + CARD_W then
        local ys = columnYs(c)
        -- Cards overlap, so the one under the point is the last one that
        -- starts above it -- the topmost of the stack at that row.
        local pick = 0
        for i = 1, #ys do
          if y >= ys[i] and y < ys[i] + CARD_H then pick = i end
        end
        if pick > 0 and pick <= game.down[c] then pick = #ys end
        return { where = "tab", a = c, i = pick }
      end
    end
  end
  return nil
end

function on.mouseDown(x, y)
  if state == "menu" or state == "paused" or state == "won" then
    on.enterKey()
    return
  end
  local h = hit(x, y)
  if h then
    cur = h
    activate()
  end
  platform.window:invalidate()
end

