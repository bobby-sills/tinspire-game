-- The sprites, as TI.Image objects, or nil if this runtime will not make them.
--
-- gc:drawImage draws a whole fruit in one call where the rects below take
-- sixty-odd, which is the difference between 64 calls and 4123 for a board
-- that repaints on every tick of a cascade. It is worth the care it needs.
--
-- The care: image.new's string form is documented only for apilevel < 2.3
-- (from 2.3 it wants a TI.ResourceHandle built by TI's own SDK), and it was
-- verified on one CX II with tools/probe/imageprobe2.lua -- one calculator, one
-- OS. So it is built inside a pcall and the whole thing is all-or-nothing: if
-- any sprite fails to build, every fruit falls back to the rects, because half
-- the board in one encoding and half in the other would look like a bug rather
-- than a fallback. The rects are not a lesser picture -- tools/fruitart.py
-- checks the two encodings against the source and against each other, pixel
-- for pixel -- they are only slower.
local sprites = (function()
  if type(image) ~= "table" or type(image.new) ~= "function" then return nil end
  local out = {}
  for i = 1, #ART do
    local built, img = pcall(image.new, ART[i].img)
    if not built or not img then return nil end
    out[i] = img
  end
  return out
end)()

