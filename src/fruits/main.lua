-- Draws fruit `kind` with its top-left at (px, py), `size` pixels square.
--
-- At the native size with images available -- which is every cell on the
-- handheld -- this is one call. Everything else goes through the rects: a cell
-- too small for a 16-pixel sprite, a fruit shrinking as it bursts, or a
-- runtime that would not build the images at all.
--
-- The scaled path maps BOTH edges of a rect through the same rounding.
-- Rounding origin and extent separately leaves one-pixel seams of background
-- between rects that should be touching, which at small sizes turns a fruit
-- into a grid of confetti.
local function drawFruit(gc, kind, px, py, size)
  local a = ART[kind]
  if not a then return end

  if sprites and size == ART_SIZE then
    gc:drawImage(sprites[kind], px, py)
    return
  end

  local pal, runs = a.pal, a.runs
  if size == ART_SIZE then
    for c = 1, #runs do
      local str = runs[c]
      if #str > 0 then
        gc:setColorRGB(pal[c * 3 - 2], pal[c * 3 - 1], pal[c * 3])
        for i = 1, #str, 4 do
          local x, y, w, h = byte(str, i, i + 3)
          gc:fillRect(px + x - ART_OFFSET, py + y - ART_OFFSET,
                      w - ART_OFFSET, h - ART_OFFSET)
        end
      end
    end
    return
  end

  for c = 1, #runs do
    local str = runs[c]
    if #str > 0 then
      gc:setColorRGB(pal[c * 3 - 2], pal[c * 3 - 1], pal[c * 3])
      for i = 1, #str, 4 do
        local x, y, w, h = byte(str, i, i + 3)
        x, y = x - ART_OFFSET, y - ART_OFFSET
        local x0 = floor(x * size / ART_SIZE)
        local y0 = floor(y * size / ART_SIZE)
        local x1 = floor((x + w - ART_OFFSET) * size / ART_SIZE)
        local y1 = floor((y + h - ART_OFFSET) * size / ART_SIZE)
        gc:fillRect(px + x0, py + y0, max(1, x1 - x0), max(1, y1 - y0))
      end
    end
  end
end

