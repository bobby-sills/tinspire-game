local function clippedRect(gc, x, y, w, h, top, bot)
  local y0 = (y < top) and top or y
  local y1 = y + h
  if y1 > bot then y1 = bot end
  if y1 <= y0 or w <= 0 then return end
  gc:fillRect(x, y0, w, y1 - y0)
end

-- Draws card `idx` with its top-left at (ox, oy), showing only the rows
-- between `top` and `bot`. That single clip does three jobs: it is how a
-- fanned card shows just its corner index, how the bottom of a long column is
-- kept inside the tableau, and how nothing is ever drawn over the status bar.
local function drawCard(gc, ox, oy, idx, top, bot)
  if oy >= bot or oy + CARD_H <= top then return end

  col(gc, CARD_BODY)
  for i = 1, #CARD_BODY_RECTS, 4 do
    clippedRect(gc, ox + CARD_BODY_RECTS[i], oy + CARD_BODY_RECTS[i + 1],
                CARD_BODY_RECTS[i + 2], CARD_BODY_RECTS[i + 3], top, bot)
  end
  col(gc, CARD_FRAME)
  for i = 1, #CARD_FRAME_RECTS, 4 do
    clippedRect(gc, ox + CARD_FRAME_RECTS[i], oy + CARD_FRAME_RECTS[i + 1],
                CARD_FRAME_RECTS[i + 2], CARD_FRAME_RECTS[i + 3], top, bot)
  end

  local entry = CARD_RUNS[idx]
  for e = 1, #entry, 2 do
    local ink, s = CARD_INK[entry[e]], entry[e + 1]
    local set = false
    for j = 1, #s, 3 do
      local y = oy + string.byte(s, j) - CARD_PACK
      -- Runs are emitted in row order, so once one is past the bottom of the
      -- visible strip the rest of this colour's runs are too.
      if y >= bot then break end
      if y >= top then
        if not set then col(gc, ink); set = true end
        gc:fillRect(ox + string.byte(s, j + 1) - CARD_PACK, y,
                    string.byte(s, j + 2) - CARD_PACK, 1)
      end
    end
  end
end

