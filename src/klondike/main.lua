end

-- os.time() alone is a poor seed: a handheld that has just been reset can
-- report the same value every launch, which would deal an identical game every
-- time. Mixing in how long the player sat on the title screen fixes that.
--
-- The seed is drawn through math.random rather than used directly, which is
-- also what lets the runtime tests pin a deal: tests/nspire_stub.lua seeds
-- math.random and neutralises math.randomseed, so this reseeding becomes a
-- no-op and the same deal comes out every run.
local function newSeed()
  local t = 0
  if os and os.time then t = os.time() or 0 end
  if os and os.clock then t = t + math.floor((os.clock() or 0) * 1000) end
  math.randomseed(t + entropy * 7919)
  math.random(); math.random()   -- first draws after a reseed are weakly mixed
  return math.random(1, 2147483646)
end

