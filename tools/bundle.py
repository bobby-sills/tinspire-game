#!/usr/bin/env python3
"""Bundle src/game.lua + src/main.lua into a single Lua script for luna.

The TI-Nspire has no `require`, so the whole game has to reach the calculator
as one file. This inlines the logic module as an immediately-invoked function
assigned to a local named `Game`, which is exactly what src/main.lua expects.

`platform.apilevel` is emitted as line 1 because the Nspire reads it before
running the script.
"""

import sys
from pathlib import Path

API_LEVEL = "2.0"

ROOT = Path(__file__).resolve().parent.parent
GAME = ROOT / "src" / "game.lua"
MAIN = ROOT / "src" / "main.lua"


def build(out_path: Path) -> None:
    game = GAME.read_text(encoding="utf-8").rstrip("\n")
    main = MAIN.read_text(encoding="utf-8").rstrip("\n")

    # Module bodies are inlined without re-indenting so that line numbers in
    # runtime errors stay close to the originals.
    parts = [
        "platform.apilevel = '%s'" % API_LEVEL,
        "",
        "-- ==========================================================",
        "--  Generated by tools/bundle.py -- do not edit this file.",
        "--  Sources: src/game.lua, src/main.lua",
        "-- ==========================================================",
        "",
        "local Game = (function()",
        game,
        "end)()",
        "",
        main,
        "",
    ]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "snake.lua"
    build(out)
    print("bundled -> %s" % out)
