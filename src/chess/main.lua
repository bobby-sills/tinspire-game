local function menuKey(key)
  local rows = 4
  if key == "up" then
    menu.row = ((menu.row - 2) % rows) + 1
  elseif key == "down" then
    menu.row = (menu.row % rows) + 1
  elseif key == "left" or key == "right" then
    local d = (key == "right") and 1 or -1
    if menu.row == 1 then
      menu.mode = (menu.mode == 1) and 2 or 1
    elseif menu.row == 2 then
      menu.level = ((menu.level - 1 + d) % #Chess.LEVELS) + 1
    elseif menu.row == 3 then
      menu.side = (menu.side == WHITE) and BLACK or WHITE
    else
      menu.autoFlip = (menu.autoFlip == 1) and 2 or 1
    end
  end
end

local function moveCursor(key)
  local c, r = cellOf(cursor)
  if key == "left" then c = c - 1
  elseif key == "right" then c = c + 1
  elseif key == "up" then r = r - 1
  elseif key == "down" then r = r + 1
  else return end
  if c < 0 or c > 7 or r < 0 or r > 7 then return end -- the board does not wrap
  cursor = squareAt(c, r)
end

local function confirm()
  if game.state == "ready" then
    newRound()
    return
  elseif game.state == "paused" then
    togglePause()
    return
  elseif game:isOver() then
    -- One press replays, so a match is a keypress apart; esc goes to the menu.
    newRound()
    return
  end

  if promo then
    local m = Chess.encode(promo.from, promo.to,
      Chess.PROMO_PIECES[promo.choice], Chess.FLAG_NORMAL)
    promo = nil
    playMove(m)
    return
  end

  if not humansTurn() then return end

  if sel then
    local m = moveTo(cursor)
    if m then
      if promotesTo(cursor) then
        -- Four pieces to choose between, so ask rather than assume a queen:
        -- underpromotion to a knight is the one that wins games.
        promo = { from = sel, to = cursor, choice = 1 }
        clearSelection()
      else
        playMove(m)
      end
    elseif cursor == sel then
      clearSelection()
    elseif not selectAt(cursor) then
      clearSelection()
    end
  else
    selectAt(cursor)
  end
end

function on.arrowKey(key)
  if game.state == "ready" then
    menuKey(key)
  elseif promo then
    if key == "left" or key == "up" then
      promo.choice = ((promo.choice - 2) % 4) + 1
    elseif key == "right" or key == "down" then
      promo.choice = (promo.choice % 4) + 1
    end
  elseif game.state == "paused" or game:isOver() then
    -- Arrows do nothing behind an overlay; enter is the way out.
  elseif humansTurn() then
    moveCursor(key)
  end
  platform.window:invalidate()
end

function on.enterKey()
  confirm()
  platform.window:invalidate()
end

function on.escapeKey()
  if promo then
    promo = nil
  elseif game.state == "ready" then
    -- Already home.
  elseif sel then
    clearSelection()
  elseif game:isOver() then
    toMenu()
  else
    togglePause()
  end
  platform.window:invalidate()
end

function on.charIn(ch)
  ch = string.lower(ch or "")
  if ch == " " then
    confirm()
  elseif ch == "u" then
    undo()
  elseif ch == "f" then
    flip = not flip
  elseif ch == "r" then
    if game.state ~= "ready" then newRound() end
  elseif ch == "m" then
    toMenu()
  elseif ch == "p" then
    if game.state ~= "ready" then togglePause() end
  end
  platform.window:invalidate()
end

-- Tapping a square is the same as moving the cursor there and pressing enter,
-- which is what the touchpad and the computer software's mouse want.
function on.mouseDown(x, y)
  if game.state ~= "playing" or promo then
    confirm()
  else
    local c = math.floor((x - ui.bx) / ui.cell)
    local r = math.floor((y - ui.by) / ui.cell)
    if c >= 0 and c <= 7 and r >= 0 and r <= 7 then
      if humansTurn() then
        cursor = squareAt(c, r)
        confirm()
      end
    end
  end
  platform.window:invalidate()
end

