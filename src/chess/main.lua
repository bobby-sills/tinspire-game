-- os.time() alone is a poor seed here: a handheld that has just been reset
-- can report the same value every launch, which would make the bot's choices
-- -- and so every Easy game -- identical every time. Mixing in how long the
-- player sat on the title screen fixes that.
local function reseed()
  local t = 0
  if os and os.time then t = os.time() or 0 end
  if os and os.clock then t = t + math.floor((os.clock() or 0) * 1000) end
  math.randomseed(t + entropy * 7919)
  math.random(); math.random() -- first draws after a reseed are weakly mixed
end

-- True when the machine is waiting on a person rather than on itself.
local function humansTurn()
  return game.state == "playing" and phase == "idle" and not game:isBotTurn()
end

-- ------------------------------------------------------- board <-> screen --
--
-- (col, row) are cells of the drawn grid, 0..7 from the top left. Which
-- square that is depends on which way round the board is, and these two are
-- exact inverses of each other -- everything else works in squares.

local function squareAt(c, r)
  if flip then return Chess.sqOf(8 - c, r + 1) end
  return Chess.sqOf(c + 1, 8 - r)
end

local function cellOf(sq)
  local f, r = Chess.fileOf(sq), Chess.rankOf(sq)
  if flip then return 8 - f, r - 1 end
  return f - 1, 8 - r
end

-- ------------------------------------------------------------- selection --

local function clearSelection()
  sel, nDests = nil, 0
end

local function selectAt(sq)
  local pc = game.board[sq]
  if pc == Chess.EMPTY or Chess.COLOR[pc] ~= game.side then return false end
  local n = game:legalMovesFrom(sq, dests)
  if n == 0 then return false end
  sel, nDests = sq, n
  return true
end

-- The move from the selected square to `sq`, or nil. Promotions come back as
-- the queen version; the chooser swaps in whichever piece the player picks.
local function moveTo(sq)
  for i = 1, nDests do
    if Chess.moveTo(dests[i]) == sq then return dests[i] end
  end
  return nil
end

local function promotesTo(sq)
  local n = 0
  for i = 1, nDests do
    if Chess.moveTo(dests[i]) == sq and Chess.movePromo(dests[i]) ~= 0 then n = n + 1 end
  end
  return n > 1
end

-- ----------------------------------------------------------- turn plumbing --

-- Hands the bot the position and lets on.timer() feed it from there.
local function startThinking()
  ai = Chess.AI.fromLevel(game, menu.level, { rand = game.rand })
  thinkTicks = 0
  phase = "thinking"
end

local function afterMove()
  clearSelection()
  promo = nil
  if game:isOver() then
    phase = "idle"
    return
  end
  -- Hot-seat play on one calculator means the two players sit on the same
  -- side of the screen, so turning the board round between turns is the
  -- closest thing to each of them getting their own view.
  if not vsBot() and menu.autoFlip == 1 then flip = (game.side == BLACK) end
  if game:isBotTurn() then startThinking() else phase = "idle" end
end

local function playMove(m)
  if not game:play(m) then return false end
  cursor = Chess.moveTo(m)
  afterMove()
  return true
end

local function newRound()
  reseed()
  game:reset({
    mode = (menu.mode == 1) and "hotseat" or "bot",
    botSide = (menu.side == WHITE) and BLACK or WHITE,
  })
  ai = nil
  phase, thinkTicks = "idle", 0
  clearSelection()
  promo = nil
  flip = (menu.mode == 2) and (menu.side == BLACK) or false
  cursor = Chess.sqOf(5, flip and 7 or 2)
  if game:isBotTurn() then startThinking() end
end

local function toMenu()
  if ai then ai:cancel() end
  ai = nil
  -- Clear the board on the way out. Leaving an abandoned game showing behind
  -- the title panel invites the player to think it is still theirs to finish.
  game:reset({})
  game.state = "ready"
  phase = "idle"
  clearSelection()
  promo = nil
end

-- Undo. In hot-seat that is one ply; against the bot it is two, because
-- taking back only the bot's reply would just hand it the same position and
-- get the same move -- what the player means is "let me play that again".
local function undo()
  if game.state ~= "playing" and not game:isOver() then return end
  if phase == "thinking" then
    if ai then ai:cancel() end
    phase = "idle"
  end
  if not game:takeback() then return end
  if vsBot() and game:isBotTurn() then game:takeback() end
  ai = nil
  clearSelection()
  promo = nil
  local last = game:lastMove()
  cursor = last and last.to or cursor
  phase = "idle"
end

local function togglePause()
  -- Pausing mid-search is fair game and throws the search away; the bot
  -- starts over on resume.
  if game.state == "playing" then
    if phase == "thinking" then
      if ai then ai:cancel() end
      phase = "idle"
    end
    game.state = "paused"
  elseif game.state == "paused" then
    game.state = "playing"
    if game:isBotTurn() then startThinking() end
  end
end

