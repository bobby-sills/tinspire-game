-- game.lua -- pure Wordle rules, and the dictionary they are checked against.
--
-- This module deliberately knows nothing about the TI-Nspire: no `platform`,
-- no `gc`, no `timer`. That keeps it runnable under a plain Lua 5.1
-- interpreter on a laptop, so the rules can be tested without a calculator.
-- All drawing, input and timing lives in src/wordle/main.lua.
--
-- The dictionary is baked in at the bottom of this file by tools/wordlist.py,
-- because the Nspire sandbox has no file I/O: whatever the game knows, it has
-- to carry inside the .tns.

local Wordle = {}
Wordle.__index = Wordle

-- ------------------------------------------------------------------ tuning --
-- The shape of the game. Everything else here is Wordle's actual rules.
local LEN  = 5   -- letters per word
local ROWS = 6   -- guesses allowed
-- ---------------------------------------------------------------------------

Wordle.LEN, Wordle.ROWS = LEN, ROWS

-- Marks are ordered, and that ordering is load-bearing: a letter's keyboard
-- colour is the *maximum* mark it has ever been given, which is what makes
-- "a letter can only ever get better" fall out of the representation instead
-- of needing a rule of its own.
local UNKNOWN, GREY, YELLOW, GREEN = 0, 1, 2, 3
Wordle.UNKNOWN, Wordle.GREY, Wordle.YELLOW, Wordle.GREEN = UNKNOWN, GREY, YELLOW, GREEN

-- Filled in by the generated block at the bottom of this file. Declared up
-- here so the functions below close over these locals rather than silently
-- reading globals of the same name.
local ANSWERS, GUESSES, N_ANSWERS, N_GUESSES

local byte, sub, char, rep = string.byte, string.sub, string.char, string.rep
local floor, min = math.floor, math.min
local A = byte("a")

-- ------------------------------------------------------------- dictionary --

-- Words are stored one per line inside a long string, so every word occupies
-- the same WORD_STRIDE bytes and the i'th is a fixed offset away. The trailing
-- newline is what costs the extra byte; it buys a dictionary that is readable
-- and diffable in the repo. See tools/wordlist.py for the measurements.
local WORD_STRIDE = LEN + 1

local function wordAt(list, i)
  local at = (i - 1) * WORD_STRIDE + 1
  return sub(list, at, at + LEN - 1)
end

-- ~14 comparisons over 11,417 words. Lua compares strings byte-wise for pure
-- lowercase ASCII, and the generator sorts in the same order, which
-- tests/wordle/run.lua confirms by finding every single word in the list.
local function find(list, n, word)
  local lo, hi = 1, n
  while lo <= hi do
    local mid = floor((lo + hi) / 2)
    local w = wordAt(list, mid)
    if w == word then
      return mid
    elseif w < word then
      lo = mid + 1
    else
      hi = mid - 1
    end
  end
  return nil
end

function Wordle.answerCount() return N_ANSWERS end
function Wordle.guessCount() return N_GUESSES end
function Wordle.answerAt(i) return wordAt(ANSWERS, i) end
function Wordle.guessAt(i) return wordAt(GUESSES, i) end

-- Is this a word the player is allowed to type? The answer pool is a subset of
-- the guess list (tools/wordlist.py refuses to emit anything else), so one
-- search over the larger list settles it.
function Wordle.isAllowed(word)
  return find(GUESSES, N_GUESSES, word) ~= nil
end

function Wordle.isAnswer(word)
  return find(ANSWERS, N_ANSWERS, word) ~= nil
end

-- ---------------------------------------------------------------- scoring --

-- The two-pass multiset rule, which is the whole game and the thing most
-- implementations get wrong.
--
-- The naive version asks "is this letter somewhere in the answer?" and
-- over-marks repeats: guess SPEED against answer ABIDE paints both E's,
-- telling the player there are two when there is one.
--
-- Pass 1 takes the exact positions and *removes those letters from the pool*,
-- so a green claims its letter before any yellow can. That ordering matters
-- even when the green sits to the right of the yellow candidate: in guess
-- ALLOW against answer LOLLY the third L is green, so only one of the two
-- earlier letters can still find an L to claim.
--
-- Pass 2 then walks left to right, which is what decides the winner when two
-- positions compete for one scarce letter: the leftmost gets it.
--
-- Note the pool is built during pass 1 from the answer letters that did *not*
-- match, which is the same thing as "initialise to the answer, then remove the
-- greens", one traversal cheaper.
function Wordle.score(guess, answer)
  local marks, pool = {}, {}

  for i = 1, LEN do
    local g, a = byte(guess, i), byte(answer, i)
    if g == a then
      marks[i] = GREEN
    else
      marks[i] = GREY
      pool[a] = (pool[a] or 0) + 1
    end
  end

  for i = 1, LEN do
    if marks[i] ~= GREEN then
      local g = byte(guess, i)
      local left = pool[g]
      if left and left > 0 then
        marks[i] = YELLOW
        pool[g] = left - 1
      end
    end
  end

  return marks
end

-- ------------------------------------------------------------------- game --

-- Accepts whatever on.charIn hands over -- which includes "", " " and "\n"
-- from the runtime tests -- and returns a single lowercase letter, or nil.
function Wordle.letterOf(ch)
  if type(ch) ~= "string" or #ch ~= 1 then return nil end
  local b = byte(ch)
  if b >= 65 and b <= 90 then b = b + 32 end
  if b < A or b > A + 25 then return nil end
  return char(b)
end

function Wordle.new(opts)
  opts = opts or {}
  local self = setmetatable({}, Wordle)
  self.rand = opts.rand or math.random
  self.hard = opts.hard and true or false
  self:reset(opts.answer)
  return self
end

-- `answer` is for tests and for nothing else; play calls this with no argument
-- and gets a word from the pool.
function Wordle:reset(answer)
  self.answer = answer or Wordle.answerAt(self.rand(N_ANSWERS))
  self.rows = {}
  self.typed = ""
  self.state = "ready"
  self.letters = {}
  for i = 1, 26 do self.letters[i] = UNKNOWN end
  -- Candidate filtering, see below. nil means "the whole answer pool", which
  -- avoids building a 2,315-entry array at reset for a count nobody has asked
  -- for yet.
  self.possible = nil
  self.filter = nil
end

function Wordle:start()
  if self.state == "ready" then self.state = "playing" end
end

function Wordle:isOver()
  return self.state == "won" or self.state == "lost"
end

function Wordle:row(n)
  return self.rows[n]
end

-- The keyboard colour for a letter: the best mark it has ever earned.
function Wordle:letterMark(letter)
  local b = byte(letter)
  if not b then return UNKNOWN end
  if b >= 65 and b <= 90 then b = b + 32 end
  return self.letters[b - A + 1] or UNKNOWN
end

function Wordle:typeLetter(ch)
  if self.state ~= "playing" then return false end
  if #self.typed >= LEN then return false end
  local letter = Wordle.letterOf(ch)
  if not letter then return false end
  self.typed = self.typed .. letter
  return true
end

function Wordle:backspace()
  if self.state ~= "playing" then return false end
  if #self.typed == 0 then return false end
  self.typed = sub(self.typed, 1, #self.typed - 1)
  return true
end

-- Hard mode: every hint already shown has to be reused.
--
-- Two separate obligations, and the duplicate handling is why this is worth
-- testing rather than eyeballing. A green pins a position. A yellow only
-- promises the letter appears *somewhere*, but a row showing the same letter
-- non-grey twice has promised it appears twice, so the requirement is a count,
-- taken as the maximum across rows rather than the sum -- two rows each
-- showing one E prove there is one E, not two.
--
-- Greens count toward that total as well as pinning their square, which is
-- what stops a letter shown green twice from being satisfiable by one copy.
--
-- Returns nil if `word` is legal, or a message naming the first thing missing.
function Wordle:hardModeViolation(word)
  local fixed, need = {}, {}

  for _, r in ipairs(self.rows) do
    local shown = {}
    for i = 1, LEN do
      local b = byte(r.word, i)
      if r.marks[i] == GREEN then fixed[i] = b end
      if r.marks[i] >= YELLOW then shown[b] = (shown[b] or 0) + 1 end
    end
    for b, n in pairs(shown) do
      if not need[b] or n > need[b] then need[b] = n end
    end
  end

  for i = 1, LEN do
    if fixed[i] and byte(word, i) ~= fixed[i] then
      return string.format("%s must be letter %d", char(fixed[i] - 32), i)
    end
  end

  local have = {}
  for i = 1, LEN do
    local b = byte(word, i)
    have[b] = (have[b] or 0) + 1
  end
  -- Ordered by letter so the message is stable rather than depending on the
  -- hash order of `need`.
  for b = A, A + 25 do
    local n = need[b]
    if n and (have[b] or 0) < n then
      if n == 1 then
        return string.format("Guess must contain %s", char(b - 32))
      end
      return string.format("Guess must contain %d %s", n, rep(char(b - 32), n))
    end
  end

  return nil
end

-- Plays the typed word. Returns true on success; on failure returns false plus
-- a reason and a message, and -- this is the part worth being careful about --
-- has changed nothing at all, so a rejected guess costs no row.
function Wordle:submit()
  if self.state ~= "playing" then return false, "over" end
  if #self.typed < LEN then return false, "short", "Not enough letters" end

  local word = self.typed
  if not Wordle.isAllowed(word) then return false, "unknown", "Not in word list" end

  if self.hard then
    local why = self:hardModeViolation(word)
    if why then return false, "hard", why end
  end

  local marks = Wordle.score(word, self.answer)
  self.rows[#self.rows + 1] = { word = word, marks = marks }

  for i = 1, LEN do
    local at = byte(word, i) - A + 1
    if marks[i] > self.letters[at] then self.letters[at] = marks[i] end
  end

  self.typed = ""
  -- Winning is checked before the row count, so a correct sixth guess wins
  -- rather than running the player out of rows.
  if word == self.answer then
    self.state = "won"
  elseif #self.rows >= ROWS then
    self.state = "lost"
  end

  return true
end

-- ------------------------------------------------- candidates, one slice at --

-- How many answers are still consistent with everything shown so far.
--
-- A candidate survives if scoring the guess against it would have produced
-- exactly the marks the player was given. That is 2,315 scorings for the first
-- guess, and there are no threads and no way to yield to the OS: run it inside
-- one on.timer() and the screen freezes and keypresses queue up, which a player
-- reads as a crash. So it is an explicit state machine with a work budget the
-- host advances one slice per tick, the same shape as connect4's search.
--
-- The pass builds a *new* list and swaps it in only when it finishes. A
-- suspended pass is suspended mid-traversal, and on.paint must never be able
-- to show a half-filtered count.

-- A full pass is 2,315 scorings, measured at 5.4 ms on this container, so
-- ~0.0023 ms a candidate. The handheld's 396MHz ARM runs interpreted Lua far
-- slower than this x86 -- call it 50x, the one number here that is an estimate
-- rather than a measurement, and good to perhaps a factor of two -- so ~435
-- candidates in a 0.05s tick. Under half of that is the budget:
Wordle.TICK_CANDIDATES = 200

-- Being wrong about the 50x degrades gracefully: the count simply takes more
-- ticks to appear. Nothing waits on it, and no rule depends on it.

function Wordle:beginFilter()
  local r = self.rows[#self.rows]
  if not r then return end
  self.filter = { i = 1, kept = {}, word = r.word, marks = r.marks, from = self.possible }
end

local function sameMarks(a, b)
  for i = 1, LEN do
    if a[i] ~= b[i] then return false end
  end
  return true
end

-- Scores up to `budget` candidates. Returns true once the pass is complete.
function Wordle:filterStep(budget)
  local f = self.filter
  if not f then return true end

  local from = f.from
  local n = from and #from or N_ANSWERS
  local last = min(f.i + budget - 1, n)

  for i = f.i, last do
    local cand = from and from[i] or wordAt(ANSWERS, i)
    if sameMarks(Wordle.score(f.word, cand), f.marks) then
      f.kept[#f.kept + 1] = cand
    end
  end

  f.i = last + 1
  if f.i > n then
    self.possible = f.kept
    self.filter = nil
    return true
  end
  return false
end

function Wordle:isFiltering()
  return self.filter ~= nil
end

-- The count, or nil while a pass is in flight -- the host shows a placeholder
-- rather than a number that is about to change.
function Wordle:remaining()
  if self.filter then return nil end
  if not self.possible then return N_ANSWERS end
  return #self.possible
end

