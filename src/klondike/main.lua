-- Setting a colour is a call and a rect is not, so the current colour is
-- tracked and re-set only when it actually changes. A whole black number card
-- comes out at two colours, because its ink is the same value as its frame.
local curR, curG, curB

local function col(gc, c)
  if c[1] ~= curR or c[2] ~= curG or c[3] ~= curB then
    gc:setColorRGB(c[1], c[2], c[3])
    curR, curG, curB = c[1], c[2], c[3]
  end
end

local function fitFont(gc, text, maxW, style)
  for _, size in ipairs(FONT_STEPS) do
    gc:setFont("sansserif", style or "r", size)
    if gc:getStringWidth(text) <= maxW then return size end
  end
  return FONT_STEPS[#FONT_STEPS]
end

-- The preview renderer anchors text at the top left, so everything is drawn
