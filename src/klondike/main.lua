function on.resize(w, h)
  ui.w, ui.h = w, h

  local gap = math.floor((w - 2 * MARGIN - COLUMNS * CARD_W) / (COLUMNS - 1))
  if gap < 0 then gap = 0 end
  if gap > GAP_MAX then gap = GAP_MAX end
  ui.gap = gap
  local contentW = COLUMNS * CARD_W + (COLUMNS - 1) * gap
  ui.x0 = math.floor((w - contentW) / 2)

  ui.topY = HUD_H + ROW_GAP
  ui.tabY = ui.topY + CARD_H + ROW_GAP
  ui.tabH = h - MARGIN - ui.tabY

  ui.fits = (w >= MIN_W) and (h >= MIN_H) and (contentW <= w - 2)

  platform.window:invalidate()
end

-- The face-down and face-up steps for a column holding D face-down cards and U
-- face-up ones, given the height the tableau has to spend on offsets.
--
-- Preference order: keep the face-up step comfortable, and buy room for it by
-- squeezing the face-down block, since those cards show nothing but the same
-- back over and over. Only when that is not enough does the face-up step drop
-- below FAN_UP_MIN.
local function fanSteps(D, U, avail)
  if avail < 0 then avail = 0 end

  local function upFor(d)
    if U <= 1 then return FAN_UP_MAX end
    local room = avail - D * d
    if room < 0 then room = 0 end
    return math.floor(room / (U - 1))
  end

  -- Spend the face-down step down one pixel at a time, stopping as soon as
  -- the face-up step is comfortable again. Jumping straight to the minimum
  -- would give a seven-card column at the deal the same cramped stack of
  -- backs as a nineteen-card one, for no reason.
  local d = FAN_DOWN_MIN
  for try = FAN_DOWN_MAX, FAN_DOWN_MIN, -1 do
    d = try
    if math.min(FAN_UP_MAX, upFor(try)) >= FAN_UP_MIN then break end
  end
  local u = math.min(FAN_UP_MAX, upFor(d))
  if u < 1 then u = 1 end

  -- Whatever the arithmetic above decided, the column must fit. A window
  -- short enough to defeat both minimums shrinks the face-down block to
  -- nothing and then the face-up step, in that order; drawCard clips the rest,
  -- so the tableau area is never overrun however long the column gets.
  local function total() return D * d + ((U > 1) and (U - 1) * u or 0) end
  while total() > avail and d > 0 do d = d - 1 end
  while total() > avail and u > 1 do u = u - 1 end

  return d, u
end

-- Where every card of a column sits, top to bottom. Returned as a flat array
-- of y positions so both the painter and the hit-tester use the same numbers
-- and cannot drift apart.
local function columnYs(c)
  local col, down = game.tab[c], game.down[c]
  local n = #col
  local ys = {}
  if n == 0 then return ys end
  local d, u = fanSteps(down, n - down, ui.tabH - CARD_H)
  local y = ui.tabY
  for i = 1, n do
    ys[i] = y
    if i <= down then y = y + d else y = y + u end
  end
  return ys
end

