local built = {}
for i, c in ipairs(CANDS) do
  local rec = { label = c[1] }
  if type(image) ~= "table" or type(image.new) ~= "function" then
    rec.status = "noapi:" .. type(image)
  else
    local okNew, img = pcall(image.new, c[2])
    if not okNew then
      rec.status = "err:" .. tostring(img):sub(1, 18)
    elseif img == nil then
      rec.status = "nil"
    else
      rec.status, rec.img = "built", img
      if type(img) == "userdata" or type(img) == "table" then
        local okW, w = pcall(function() return img:width() end)
        local okH, h = pcall(function() return img:height() end)
        if okW and okH then rec.status = "built " .. tostring(w) .. "x" .. tostring(h) end
      end
    end
  end
  built[i] = rec
end

local ui = { w = 318, h = 212 }

function on.resize(w, h)
  ui.w, ui.h = w, h
  platform.window:invalidate()
end

function on.paint(gc)
  gc:setColorRGB(16, 18, 24)
  gc:fillRect(0, 0, ui.w, ui.h)

  gc:setFont("sansserif", "b", 10)
  gc:setColorRGB(240, 240, 245)
  gc:drawString("TI.Image probe 2 -- apilevel " .. tostring(platform.apilevel), 4, 2, "top")

  gc:setFont("sansserif", "r", 9)
  local y = 20
  for i, rec in ipairs(built) do
    -- Control bar: if you can see this, the slot was reached and painted.
    gc:setColorRGB(60, 200, 90)
    gc:fillRect(4, y, 3, 18)

    gc:setColorRGB(190, 196, 210)
    gc:drawString(i .. ". " .. rec.label, 12, y, "top")

    -- Outlined landing box, so an absent image is obvious rather than ambiguous.
    local ix = 232
    gc:setColorRGB(80, 86, 100)
    gc:drawRect(ix - 1, y - 1, 18, 18)

    local shown = rec.status
    if rec.img then
      local okDraw, err = pcall(function() gc:drawImage(rec.img, ix, y) end)
      if not okDraw then shown = "draw!" .. tostring(err):sub(1, 14) end
    end

    gc:setColorRGB(150, 156, 172)
    gc:drawString(shown, 12, y + 10, "top")
    y = y + 34
  end

  gc:setColorRGB(120, 128, 148)
  gc:drawString("1 white square  2 magenta  3+4 an apple  5 must stay blank",
                4, ui.h - 12, "top")
end

