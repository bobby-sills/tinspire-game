local function confirm()
  local s = board.state
  if s == "ready" then
    beginRound()
  elseif s == "over" then
    newRound()
    board:start()
  elseif s == "paused" then
    board:resume()
  elseif s == "playing" and board.phase == "idle" then
    -- enter picks a fruit up, and puts it back down.
    if sel and sel.x == cur.x and sel.y == cur.y then
      sel = nil
    else
      sel = { x = cur.x, y = cur.y }
    end
  end
end

