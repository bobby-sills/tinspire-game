-- Sets the largest supported font the text fits `maxW` in, and returns it.
-- Font metrics are not knowable until runtime, so every box on screen is
-- sized from the font rather than from a character count.
local function fitFont(gc, text, maxW, style)
  local size = FONT_SIZES[#FONT_SIZES]
  for _, s in ipairs(FONT_SIZES) do
    gc:setFont("sansserif", style or "r", s)
    size = s
    if gc:getStringWidth(text) <= maxW then break end
  end
  return size
end

